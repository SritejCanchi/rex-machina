def steptoward():
    """StepToward(From, Target) -> the neighbour of From that is in bounds and
    strictly closer to Target, else From itself.

    game.js iterates STEP in the order left, right, up, down and keeps the
    first candidate strictly closer than the best so far. A single orthogonal
    step changes Manhattan distance by exactly one, so nothing after the first
    strict improvement can beat it: the loop is really "the first direction in
    that order that closes the gap". That collapses to arithmetic -- no branch
    node, no Select, and so no node class this generator cannot already emit.

    "Strictly closer" along an axis is just the sign of the delta:

        wantLeft = dx < 0    wantRight = dx > 0
        wantUp   = dy < 0    wantDown  = dy > 0

    The InBounds guard cannot be dropped even though From and Target are both
    on the grid, because Predict deliberately returns an off-grid tile when the
    dog is against a fence -- Rex chasing (-1,0) from (0,3) has to go up, not
    off the board. That case is a self-test assertion.

    The winning direction becomes a +1/-1 offset through
    Conv_BoolToInt -> Conv_IntToDouble, so the whole body is one straight-line
    arithmetic chain.
    """
    nodes = []

    def n(name, member, x, y, lib=MATH):
        node = Node(name, member, x, y, lib=lib)
        nodes.append(node)
        return node

    def out(node, pinname, typefrag, links):
        """Set an output pin's link list after the consumers are known."""
        for i, t in enumerate(node.pins):
            if t[0] == pinname:
                node.pins[i] = t[:4] + (links,) + t[5:]
                return
        node.pin(pinname, "out", typefrag, None, links)

    # ---- unpack both tiles -------------------------------------------------
    bf = n("RM_StBF", "BreakVector2D", -2100, -260)
    bt = n("RM_StBT", "BreakVector2D", -2100, -80)
    bf.pin("InVec", "in", T_V2D)
    bt.pin("InVec", "in", T_V2D)

    dx = n("RM_StDX", "Subtract_DoubleDouble", -1900, -260)
    dy = n("RM_StDY", "Subtract_DoubleDouble", -1900, -140)
    dx.pin("A", "in", T_DOUBLE, "0.0", [(bt.name, bt.pid("X"))])
    dx.pin("B", "in", T_DOUBLE, "0.0", [(bf.name, bf.pid("X"))])
    dy.pin("A", "in", T_DOUBLE, "0.0", [(bt.name, bt.pid("Y"))])
    dy.pin("B", "in", T_DOUBLE, "0.0", [(bf.name, bf.pid("Y"))])
    out(bt, "X", T_DOUBLE, [(dx.name, dx.pid("A"))])
    out(bt, "Y", T_DOUBLE, [(dy.name, dy.pid("A"))])

    fx = [(dx.name, dx.pid("B"))]          # consumers of From.X
    fy = [(dy.name, dy.pid("B"))]          # consumers of From.Y
    dxc, dyc = [], []                      # consumers of dx / dy

    # ---- one candidate per direction, in game.js's order -------------------
    DIRS = [("L", "X", -1, "Less_DoubleDouble"),
            ("R", "X", +1, "Greater_DoubleDouble"),
            ("U", "Y", -1, "Less_DoubleDouble"),
            ("D", "Y", +1, "Greater_DoubleDouble")]
    ok, row = {}, -560
    for tag, axis, step, cmp_member in DIRS:
        delta, dcons = (dx, dxc) if axis == "X" else (dy, dyc)

        want = n("RM_StW" + tag, cmp_member, -1700, row)
        want.pin("A", "in", T_DOUBLE, "0.0", [(delta.name, delta.pid("ReturnValue"))])
        want.pin("B", "in", T_DOUBLE, "0.0")
        dcons.append((want.name, want.pid("A")))

        shift = n("RM_StC" + tag,
                  "Add_DoubleDouble" if step > 0 else "Subtract_DoubleDouble",
                  -1700, row + 110)
        shift.pin("A", "in", T_DOUBLE, "0.0", [(bf.name, bf.pid(axis))])
        shift.pin("B", "in", T_DOUBLE, "1.0")
        shift.pin("ReturnValue", "out", T_DOUBLE)
        (fx if axis == "X" else fy).append((shift.name, shift.pid("A")))

        cand = n("RM_StV" + tag, "MakeVector2D", -1480, row + 110)
        if axis == "X":
            cand.pin("X", "in", T_DOUBLE, "0.0", [(shift.name, shift.pid("ReturnValue"))])
            cand.pin("Y", "in", T_DOUBLE, "0.0", [(bf.name, bf.pid("Y"))])
            fy.append((cand.name, cand.pid("Y")))
        else:
            cand.pin("X", "in", T_DOUBLE, "0.0", [(bf.name, bf.pid("X"))])
            fx.append((cand.name, cand.pid("X")))
            cand.pin("Y", "in", T_DOUBLE, "0.0", [(shift.name, shift.pid("ReturnValue"))])
        out(shift, "ReturnValue", T_DOUBLE, [(cand.name, cand.pid("X" if axis == "X" else "Y"))])

        ib = n("RM_StI" + tag, "InBounds", -1260, row + 110, lib=SELF_CTX)
        ib.pin("Tile", "in", T_V2D, None, [(cand.name, cand.pid("ReturnValue"))])
        out(cand, "ReturnValue", T_V2D, [(ib.name, ib.pid("Tile"))])

        a = n("RM_StOK" + tag, "BooleanAND", -1040, row + 55)
        a.pin("A", "in", T_BOOL, "false", [(want.name, want.pid("ReturnValue"))])
        a.pin("B", "in", T_BOOL, "false", [(ib.name, ib.pid("Inside"))])
        out(want, "ReturnValue", T_BOOL, [(a.name, a.pid("A"))])
        out(ib, "Inside", T_BOOL, [(a.name, a.pid("B"))])
        ok[tag] = a
        row += 300

    # ---- first true wins ---------------------------------------------------
    # sel(L) = ok(L); sel(R) = ok(R) and not (L); sel(U) = ok(U) and not (L or R) ...
    sel = {"L": ok["L"]}
    okc = {t: [] for t in ok}              # consumers of each ok(tag)
    seen, seenc = ok["L"], okc["L"]        # "an earlier direction already won"
    for i, tag in enumerate(("R", "U", "D")):
        nt = n("RM_StN" + tag, "Not_PreBool", -860, -520 + i * 300)
        nt.pin("A", "in", T_BOOL, "false", [(seen.name, seen.pid("ReturnValue"))])
        seenc.append((nt.name, nt.pid("A")))
        s2 = n("RM_StS" + tag, "BooleanAND", -680, -520 + i * 300)
        s2.pin("A", "in", T_BOOL, "false", [(ok[tag].name, ok[tag].pid("ReturnValue"))])
        s2.pin("B", "in", T_BOOL, "false", [(nt.name, nt.pid("ReturnValue"))])
        out(nt, "ReturnValue", T_BOOL, [(s2.name, s2.pid("B"))])
        okc[tag].append((s2.name, s2.pid("A")))
        sel[tag] = s2
        if tag != "D":
            orn = n("RM_StOr" + tag, "BooleanOR", -860, -420 + i * 300)
            orn.pin("A", "in", T_BOOL, "false", [(seen.name, seen.pid("ReturnValue"))])
            orn.pin("B", "in", T_BOOL, "false", [(ok[tag].name, ok[tag].pid("ReturnValue"))])
            seenc.append((orn.name, orn.pid("A")))
            okc[tag].append((orn.name, orn.pid("B")))
            out(seen, "ReturnValue", T_BOOL, seenc)
            seen, seenc = orn, []
        else:
            out(seen, "ReturnValue", T_BOOL, seenc)

    # ---- the chosen direction becomes a +1 / -1 offset ----------------------
    offs = {}
    for i, tag in enumerate(("L", "R", "U", "D")):
        bi = n("RM_StB2I" + tag, "Conv_BoolToInt", -500, -520 + i * 160)
        bi.pin("InBool", "in", T_BOOL, "false", [(sel[tag].name, sel[tag].pid("ReturnValue"))])
        i2d = n("RM_StI2D" + tag, "Conv_IntToDouble", -340, -520 + i * 160)
        i2d.pin("InInt", "in", T_INT, "0", [(bi.name, bi.pid("ReturnValue"))])
        out(bi, "ReturnValue", T_INT, [(i2d.name, i2d.pid("InInt"))])
        if tag == "L":
            okc["L"].append((bi.name, bi.pid("InBool")))
            out(sel["L"], "ReturnValue", T_BOOL, okc["L"])
        else:
            out(sel[tag], "ReturnValue", T_BOOL, [(bi.name, bi.pid("InBool"))])
        offs[tag] = i2d
    for tag in ("R", "U", "D"):
        out(ok[tag], "ReturnValue", T_BOOL, okc[tag])

    offx = n("RM_StOffX", "Subtract_DoubleDouble", -180, -520)
    offx.pin("A", "in", T_DOUBLE, "0.0", [(offs["R"].name, offs["R"].pid("ReturnValue"))])
    offx.pin("B", "in", T_DOUBLE, "0.0", [(offs["L"].name, offs["L"].pid("ReturnValue"))])
    offy = n("RM_StOffY", "Subtract_DoubleDouble", -180, -360)
    offy.pin("A", "in", T_DOUBLE, "0.0", [(offs["D"].name, offs["D"].pid("ReturnValue"))])
    offy.pin("B", "in", T_DOUBLE, "0.0", [(offs["U"].name, offs["U"].pid("ReturnValue"))])
    for tag, node, pin in (("R", offx, "A"), ("L", offx, "B"),
                           ("D", offy, "A"), ("U", offy, "B")):
        out(offs[tag], "ReturnValue", T_DOUBLE, [(node.name, node.pid(pin))])

    nx = n("RM_StNX", "Add_DoubleDouble", -20, -520)
    nx.pin("A", "in", T_DOUBLE, "0.0", [(bf.name, bf.pid("X"))])
    nx.pin("B", "in", T_DOUBLE, "0.0", [(offx.name, offx.pid("ReturnValue"))])
    ny = n("RM_StNY", "Add_DoubleDouble", -20, -360)
    ny.pin("A", "in", T_DOUBLE, "0.0", [(bf.name, bf.pid("Y"))])
    ny.pin("B", "in", T_DOUBLE, "0.0", [(offy.name, offy.pid("ReturnValue"))])
    out(offx, "ReturnValue", T_DOUBLE, [(nx.name, nx.pid("B"))])
    out(offy, "ReturnValue", T_DOUBLE, [(ny.name, ny.pid("B"))])
    fx.append((nx.name, nx.pid("A")))
    fy.append((ny.name, ny.pid("A")))

    mk = n("RM_StMake", "MakeVector2D", 160, -440)
    mk.pin("X", "in", T_DOUBLE, "0.0", [(nx.name, nx.pid("ReturnValue"))])
    mk.pin("Y", "in", T_DOUBLE, "0.0", [(ny.name, ny.pid("ReturnValue"))])
    mk.pin("ReturnValue", "out", T_V2D)
    out(nx, "ReturnValue", T_DOUBLE, [(mk.name, mk.pid("X"))])
    out(ny, "ReturnValue", T_DOUBLE, [(mk.name, mk.pid("Y"))])

    out(bf, "X", T_DOUBLE, fx)
    out(bf, "Y", T_DOUBLE, fy)
    out(dx, "ReturnValue", T_DOUBLE, dxc)
    out(dy, "ReturnValue", T_DOUBLE, dyc)
    return nodes


def predict():
    """Predict() -> the tile the dog is about to step onto.

    game.js:

        const w = recentMoves().filter(m => STEP[m]);   // last 4, no "wait"
        if(!w.length) return S.dog.slice();
        const c = {}; for(const m of w) c[m] = (c[m]||0)+1;
        const best = Object.keys(c).sort((a,b)=>c[b]-c[a])[0];
        return [S.dog[0]+STEP[best][0], S.dog[1]+STEP[best][1]];

    Two details in that are easy to miss and both are load-bearing.

    The sort is stable and `Object.keys` is in first-insertion order, so a tie
    on count goes to whichever direction appeared *earliest* in the window. A
    four-move window ties constantly -- left,right,left,right is a tie -- so
    this is not a corner case, it is most of the time.

    And the returned tile is deliberately allowed off the grid: a dog against
    the west fence still moving left predicts x = -1. StepToward's InBounds
    guard is what copes with that, which is why that guard has its own
    assertion.

    Both fall out of scoring each direction by *which* slots it matched rather
    than how many:

        score(d) = sum of W[i] over slots i where move[i] == d
        W = [18, 14, 12, 11]      slot 0 is the oldest of the last four

    Every subset sum of W is distinct, so no two directions can tie. The gaps
    are wide enough that more matches always outscores fewer -- the smallest
    two-match sum, 12+11, beats the largest one-match, 18 -- and within an
    equal count the weights are ordered so the earliest slot dominates, which
    is exactly the stable-sort rule. So the whole thing is straight-line
    arithmetic: no branch, no loop, no map.

    The empty case needs no special path either. If nothing matched, every
    score is zero, `any` is false, every win flag is false, the offset is
    (0,0), and the function returns DogTile unchanged -- which is what game.js
    does when the window has no directional moves in it.
    """
    W = [18, 14, 12, 11]
    DIRS = ["left", "right", "up", "down"]
    nodes = []

    def n(node):
        nodes.append(node)
        return node

    def call(name, member, x, y, lib=MATH):
        return n(Node(name, member, x, y, lib=lib))

    def link(a, apin, b, bpin):
        """Wire a.apin -> b.bpin, declaring both ends."""
        for node, pinname, other, otherpin in ((a, apin, b, bpin), (b, bpin, a, apin)):
            for i, t in enumerate(node.pins):
                if t[0] == pinname:
                    node.pins[i] = (t[:4] + (list(t[4]) + [(other.name, other.pid(otherpin))],)
                                    + t[5:])
                    break

    T_STRARR_CAT = 'PinType.PinCategory="string",PinType.PinSubCategory="",PinType.PinSubCategoryObject=None'

    # ---- the move history --------------------------------------------------
    moves = n(VarGet("RM_PdMoves", "Moves", T_STRARR_CAT, -2600, -600, tail=TAIL_ARRAY))
    length = n(ArrayLength("RM_PdLen", -2400, -600))
    moves.links.append((length.name, length.pid("TargetArray")))
    length.array_links.append((moves.name, moves.out_pin()))

    # ---- the last four slots, oldest first ---------------------------------
    valid, item = [], []
    for i in range(4):
        row = -900 + i * 260
        idx = call("RM_PdIdx%d" % i, "Add_IntInt", -2200, row)
        idx.pin("A", "in", T_INT, "0", [(length.name, length.pid("ReturnValue"))])
        idx.pin("B", "in", T_INT, "%d" % (i - 4))
        idx.pin("ReturnValue", "out", T_INT)
        length.out_links.append((idx.name, idx.pid("A")))

        ok = call("RM_PdOk%d" % i, "GreaterEqual_IntInt", -2000, row - 60)
        ok.pin("A", "in", T_INT, "0", [(idx.name, idx.pid("ReturnValue"))])
        ok.pin("B", "in", T_INT, "0")
        ok.pin("ReturnValue", "out", T_INT)     # retyped below

        safe = call("RM_PdSafe%d" % i, "Max", -2000, row + 40)
        safe.pin("A", "in", T_INT, "0", [(idx.name, idx.pid("ReturnValue"))])
        safe.pin("B", "in", T_INT, "0")
        safe.pin("ReturnValue", "out", T_INT)
        link(idx, "ReturnValue", ok, "A")
        link(idx, "ReturnValue", safe, "A")
        # the two links above were added twice by construction; keep one each
        idx.pins[2] = idx.pins[2][:4] + ([(ok.name, ok.pid("A")),
                                          (safe.name, safe.pid("A"))],) + idx.pins[2][5:]
        ok.pins[0] = ok.pins[0][:4] + ([(idx.name, idx.pid("ReturnValue"))],) + ok.pins[0][5:]
        safe.pins[0] = safe.pins[0][:4] + ([(idx.name, idx.pid("ReturnValue"))],) + safe.pins[0][5:]
        ok.pins[2] = ok.pins[2][:3] + (None, [], None)   # bool output, links later

        get = n(ArrayGet("RM_PdGet%d" % i, -1800, row + 40))
        get.array_links.append((moves.name, moves.out_pin()))
        moves.links.append((get.name, get.pid("Array")))
        get.index_links.append((safe.name, safe.pid("ReturnValue")))
        safe.pins[2] = safe.pins[2][:4] + ([(get.name, get.pid("Dimension 1"))],) + safe.pins[2][5:]
        valid.append(ok)
        item.append(get)

    # GreaterEqual_IntInt returns a bool; fix the pin type now that it is built
    for ok in valid:
        ok.pins[2] = ("ReturnValue", "out", T_BOOL, None, [], None)

    # ---- score each direction ----------------------------------------------
    score = {}
    for di, d in enumerate(DIRS):
        col = -1500 + di * 40
        parts = []
        for i in range(4):
            row = -900 + i * 260 + di * 55
            eq = call("RM_PdEq%s%d" % (d[:1].upper(), i), "EqualEqual_StrStr", col, row, lib=STR)
            eq.pin("A", "in", T_STR, None, [(item[i].name, item[i].pid("Output"))])
            eq.pin("B", "in", T_STR, d)
            eq.pin("ReturnValue", "out", T_BOOL)
            item[i].out_links.append((eq.name, eq.pid("A")))

            hit = call("RM_PdHit%s%d" % (d[:1].upper(), i), "BooleanAND", col + 180, row)
            hit.pin("A", "in", T_BOOL, "false", [(eq.name, eq.pid("ReturnValue"))])
            hit.pin("B", "in", T_BOOL, "false", [(valid[i].name, valid[i].pid("ReturnValue"))])
            hit.pin("ReturnValue", "out", T_BOOL)
            eq.pins[2] = eq.pins[2][:4] + ([(hit.name, hit.pid("A"))],) + eq.pins[2][5:]
            valid[i].pins[2] = (valid[i].pins[2][:4]
                                + (list(valid[i].pins[2][4]) + [(hit.name, hit.pid("B"))],)
                                + valid[i].pins[2][5:])

            b2i = call("RM_PdB%s%d" % (d[:1].upper(), i), "Conv_BoolToInt", col + 340, row)
            b2i.pin("InBool", "in", T_BOOL, "false", [(hit.name, hit.pid("ReturnValue"))])
            b2i.pin("ReturnValue", "out", T_INT)
            hit.pins[2] = hit.pins[2][:4] + ([(b2i.name, b2i.pid("InBool"))],) + hit.pins[2][5:]

            wt = call("RM_PdW%s%d" % (d[:1].upper(), i), "Multiply_IntInt", col + 480, row)
            wt.pin("A", "in", T_INT, "0", [(b2i.name, b2i.pid("ReturnValue"))])
            wt.pin("B", "in", T_INT, "%d" % W[i])
            wt.pin("ReturnValue", "out", T_INT)
            b2i.pins[1] = b2i.pins[1][:4] + ([(wt.name, wt.pid("A"))],) + b2i.pins[1][5:]
            parts.append(wt)

        score[d] = _sum_ints(call, link, "RM_PdS%s" % d[:1].upper(), parts, col + 640, -900 + di * 55)

    # ---- pick the winner ---------------------------------------------------
    total = _sum_ints(call, link, "RM_PdTot", list(score.values()), -600, -1000)
    any_move = call("RM_PdAny", "Greater_IntInt", -420, -1000)
    any_move.pin("A", "in", T_INT, "0", [(total.name, total.pid("ReturnValue"))])
    any_move.pin("B", "in", T_INT, "0")
    any_move.pin("ReturnValue", "out", T_BOOL)
    link(total, "ReturnValue", any_move, "A")

    m1 = call("RM_PdMax1", "Max", -600, -700)
    m2 = call("RM_PdMax2", "Max", -600, -600)
    best = call("RM_PdBest", "Max", -440, -650)
    for node, (a, b) in ((m1, (score["left"], score["right"])),
                         (m2, (score["up"], score["down"]))):
        node.pin("A", "in", T_INT, "0")
        node.pin("B", "in", T_INT, "0")
        node.pin("ReturnValue", "out", T_INT)
        link(a, "ReturnValue", node, "A")
        link(b, "ReturnValue", node, "B")
    best.pin("A", "in", T_INT, "0")
    best.pin("B", "in", T_INT, "0")
    best.pin("ReturnValue", "out", T_INT)
    link(m1, "ReturnValue", best, "A")
    link(m2, "ReturnValue", best, "B")

    win = {}
    for di, d in enumerate(DIRS):
        eq = call("RM_PdIs%s" % d[:1].upper(), "EqualEqual_IntInt", -280, -800 + di * 120)
        eq.pin("A", "in", T_INT, "0")
        eq.pin("B", "in", T_INT, "0")
        eq.pin("ReturnValue", "out", T_BOOL)
        link(score[d], "ReturnValue", eq, "A")
        link(best, "ReturnValue", eq, "B")
        w = call("RM_PdWin%s" % d[:1].upper(), "BooleanAND", -120, -800 + di * 120)
        w.pin("A", "in", T_BOOL, "false")
        w.pin("B", "in", T_BOOL, "false")
        w.pin("ReturnValue", "out", T_BOOL)
        link(eq, "ReturnValue", w, "A")
        link(any_move, "ReturnValue", w, "B")
        win[d] = w

    # ---- winner -> offset --------------------------------------------------
    ints = {}
    for di, d in enumerate(DIRS):
        c = call("RM_PdC%s" % d[:1].upper(), "Conv_BoolToInt", 40, -800 + di * 120)
        c.pin("InBool", "in", T_BOOL, "false")
        c.pin("ReturnValue", "out", T_INT)
        link(win[d], "ReturnValue", c, "InBool")
        ints[d] = c

    offs = {}
    for axis, (plus, minus, row) in (("X", ("right", "left", -800)),
                                     ("Y", ("down", "up", -660))):
        sub = call("RM_PdOff%s" % axis, "Subtract_IntInt", 220, row)
        sub.pin("A", "in", T_INT, "0")
        sub.pin("B", "in", T_INT, "0")
        sub.pin("ReturnValue", "out", T_INT)
        link(ints[plus], "ReturnValue", sub, "A")
        link(ints[minus], "ReturnValue", sub, "B")
        cv = call("RM_PdD%s" % axis, "Conv_IntToDouble", 380, row)
        cv.pin("InInt", "in", T_INT, "0")
        cv.pin("ReturnValue", "out", T_DOUBLE)
        link(sub, "ReturnValue", cv, "InInt")
        offs[axis] = cv

    # ---- DogTile + offset --------------------------------------------------
    dog = n(VarGet("RM_PdDog", "DogTile", T_V2D, 380, -480))
    br = call("RM_PdBr", "BreakVector2D", 540, -480)
    br.pin("InVec", "in", T_V2D)
    br.pin("X", "out", T_DOUBLE, "0.0")
    br.pin("Y", "out", T_DOUBLE, "0.0")
    dog.links.append((br.name, br.pid("InVec")))
    br.pins[0] = br.pins[0][:4] + ([(dog.name, dog.out_pin())],) + br.pins[0][5:]

    mk = call("RM_PdMake", "MakeVector2D", 880, -560)
    for axis, pin in (("X", "X"), ("Y", "Y")):
        add = call("RM_PdAdd%s" % axis, "Add_DoubleDouble", 700,
                   -600 if axis == "X" else -480)
        add.pin("A", "in", T_DOUBLE, "0.0")
        add.pin("B", "in", T_DOUBLE, "0.0")
        add.pin("ReturnValue", "out", T_DOUBLE)
        link(br, axis, add, "A")
        link(offs[axis], "ReturnValue", add, "B")
        mk.pin(pin, "in", T_DOUBLE, "0.0")
        link(add, "ReturnValue", mk, pin)
    mk.pin("ReturnValue", "out", T_V2D)
    return nodes


def _sum_ints(call, link, prefix, parts, x, y):
    """Add a list of int-producing nodes pairwise; return the final node."""
    level, tier = list(parts), 0
    while len(level) > 1:
        nxt = []
        for i in range(0, len(level), 2):
            if i + 1 == len(level):
                nxt.append(level[i])
                continue
            a = call("%s_%d_%d" % (prefix, tier, i), "Add_IntInt", x + tier * 140, y + i * 60)
            a.pin("A", "in", T_INT, "0")
            a.pin("B", "in", T_INT, "0")
            a.pin("ReturnValue", "out", T_INT)
            link(level[i], "ReturnValue", a, "A")
            link(level[i + 1], "ReturnValue", a, "B")
            nxt.append(a)
        level, tier = nxt, tier + 1
    return level[0]


def rexact():
    """RexAct -- one robot turn, and the single most important graph here.

    GDD 6.1, step 4:

        Move = StepToward(RexTile, Predicted)
        if Manhattan(Move, DogTile) > Before:  Move = StepToward(RexTile, DogTile)

    That is the veto. Rex commits to its prediction right up until committing
    would put it further from the dog than it already was, and then it stops
    predicting and cuts inside. Without it the player leads the robot away with
    a repeating pattern and the fight becomes free; tests/sim.js asserts the
    invariant every round of every run, and so does the self-test here.

    Choosing between two tiles needs no branch. `veto` is a bool, so

        final = A + veto * (B - A)

    componentwise is the same selection, and keeps the whole body pure up to
    the two writes at the end.

    "Did it move" is Manhattan(final, RexTile) > 0 rather than a vector
    inequality, which reuses a function that is already asserted instead of
    reaching for NotEqual_Vector2DVector2D.

    The charge line is GDD 6.1 step 6 with RM-002's clamp:

        Charge = clamp(Charge - (Moved ? PursuitCost : HoldCost) + SolarRecovery, 0, 100)

    and the ternary is folded the same way: cost = Hold + moved * (Pursuit - Hold).
    """
    nodes = []

    def n(node):
        nodes.append(node)
        return node

    def call(name, member, x, y, lib=MATH):
        return n(Node(name, member, x, y, lib=lib))

    def link(a, apin, b, bpin):
        for node, pinname, other, otherpin in ((a, apin, b, bpin), (b, bpin, a, apin)):
            for i, t in enumerate(node.pins):
                if t[0] == pinname:
                    node.pins[i] = (t[:4] + (list(t[4]) + [(other.name, other.pid(otherpin))],)
                                    + t[5:])
                    break

    def vlink(vnode, b, bpin):
        """VarGet -> some pin. VarGet keeps its links in a plain list."""
        vnode.links.append((b.name, b.pid(bpin)))
        for i, t in enumerate(b.pins):
            if t[0] == bpin:
                b.pins[i] = (t[:4] + (list(t[4]) + [(vnode.name, vnode.out_pin())],) + t[5:])
                break

    # ---- state ------------------------------------------------------------
    rex = n(VarGet("RM_RaRex", "RexTile", T_V2D, -2200, -400))
    rex2 = n(VarGet("RM_RaRex2", "RexTile", T_V2D, -2200, -200))
    rex3 = n(VarGet("RM_RaRex3", "RexTile", T_V2D, -2200, 0))
    rex4 = n(VarGet("RM_RaRex4", "RexTile", T_V2D, -1400, 400))
    dog = n(VarGet("RM_RaDog", "DogTile", T_V2D, -2200, -300))
    dog2 = n(VarGet("RM_RaDog2", "DogTile", T_V2D, -2200, -100))
    dog3 = n(VarGet("RM_RaDog3", "DogTile", T_V2D, -1800, 100))

    pred = call("RM_RaPredict", "Predict", -3000, -1000, lib=SELF_CTX)
    pred.pin("Predicted", "out", T_V2D)

    before = call("RM_RaBefore", "Manhattan", -1900, -350, lib=SELF_CTX,
                  )
    before.pin("A", "in", T_V2D)
    before.pin("B", "in", T_V2D)
    before.pin("Distance", "out", T_INT, "0")
    vlink(rex, before, "A")
    vlink(dog, before, "B")

    move_a = call("RM_RaMoveA", "StepToward", -1700, -600, lib=SELF_CTX)
    move_a.pin("From", "in", T_V2D)
    move_a.pin("Target", "in", T_V2D)
    move_a.pin("Step", "out", T_V2D)
    vlink(rex2, move_a, "From")
    link(pred, "Predicted", move_a, "Target")

    dist_a = call("RM_RaDistA", "Manhattan", -1450, -600, lib=SELF_CTX)
    dist_a.pin("A", "in", T_V2D)
    dist_a.pin("B", "in", T_V2D)
    dist_a.pin("Distance", "out", T_INT, "0")
    link(move_a, "Step", dist_a, "A")
    vlink(dog2, dist_a, "B")

    veto = call("RM_RaVeto", "Greater_IntInt", -1250, -600)
    veto.pin("A", "in", T_INT, "0")
    veto.pin("B", "in", T_INT, "0")
    veto.pin("ReturnValue", "out", T_BOOL)
    link(dist_a, "Distance", veto, "A")
    link(before, "Distance", veto, "B")

    move_b = call("RM_RaMoveB", "StepToward", -1700, -100, lib=SELF_CTX)
    move_b.pin("From", "in", T_V2D)
    move_b.pin("Target", "in", T_V2D)
    move_b.pin("Step", "out", T_V2D)
    vlink(rex3, move_b, "From")
    vlink(dog3, move_b, "Target")

    # ---- final = A + veto * (B - A) ---------------------------------------
    vf = call("RM_RaVetoI", "Conv_BoolToInt", -1080, -600)
    vf.pin("InBool", "in", T_BOOL, "false")
    vf.pin("ReturnValue", "out", T_INT)
    link(veto, "ReturnValue", vf, "InBool")
    vd = call("RM_RaVetoD", "Conv_IntToDouble", -940, -600)
    vd.pin("InInt", "in", T_INT, "0")
    vd.pin("ReturnValue", "out", T_DOUBLE)
    link(vf, "ReturnValue", vd, "InInt")

    ba = call("RM_RaBrA", "BreakVector2D", -1450, -420)
    ba.pin("InVec", "in", T_V2D)
    ba.pin("X", "out", T_DOUBLE, "0.0")
    ba.pin("Y", "out", T_DOUBLE, "0.0")
    link(move_a, "Step", ba, "InVec")
    bb = call("RM_RaBrB", "BreakVector2D", -1450, -100)
    bb.pin("InVec", "in", T_V2D)
    bb.pin("X", "out", T_DOUBLE, "0.0")
    bb.pin("Y", "out", T_DOUBLE, "0.0")
    link(move_b, "Step", bb, "InVec")

    final = call("RM_RaFinal", "MakeVector2D", -400, -300)
    for axis, row in (("X", -350), ("Y", -180)):
        d = call("RM_RaD%s" % axis, "Subtract_DoubleDouble", -1150, row)
        d.pin("A", "in", T_DOUBLE, "0.0")
        d.pin("B", "in", T_DOUBLE, "0.0")
        d.pin("ReturnValue", "out", T_DOUBLE)
        link(bb, axis, d, "A")
        link(ba, axis, d, "B")
        m = call("RM_RaM%s" % axis, "Multiply_DoubleDouble", -900, row)
        m.pin("A", "in", T_DOUBLE, "0.0")
        m.pin("B", "in", T_DOUBLE, "0.0")
        m.pin("ReturnValue", "out", T_DOUBLE)
        link(d, "ReturnValue", m, "A")
        link(vd, "ReturnValue", m, "B")
        a = call("RM_RaA%s" % axis, "Add_DoubleDouble", -650, row)
        a.pin("A", "in", T_DOUBLE, "0.0")
        a.pin("B", "in", T_DOUBLE, "0.0")
        a.pin("ReturnValue", "out", T_DOUBLE)
        link(ba, axis, a, "A")
        link(m, "ReturnValue", a, "B")
        final.pin(axis, "in", T_DOUBLE, "0.0")
        link(a, "ReturnValue", final, axis)
    final.pin("ReturnValue", "out", T_V2D)

    # ---- did it move ------------------------------------------------------
    movedist = call("RM_RaMoveDist", "Manhattan", -200, 400, lib=SELF_CTX)
    movedist.pin("A", "in", T_V2D)
    movedist.pin("B", "in", T_V2D)
    movedist.pin("Distance", "out", T_INT, "0")
    link(final, "ReturnValue", movedist, "A")
    vlink(rex4, movedist, "B")
    moved = call("RM_RaMoved", "Greater_IntInt", 0, 400)
    moved.pin("A", "in", T_INT, "0")
    moved.pin("B", "in", T_INT, "0")
    moved.pin("ReturnValue", "out", T_BOOL)
    link(movedist, "Distance", moved, "A")

    mi = call("RM_RaMovedI", "Conv_BoolToInt", 160, 400)
    mi.pin("InBool", "in", T_BOOL, "false")
    mi.pin("ReturnValue", "out", T_INT)
    link(moved, "ReturnValue", mi, "InBool")
    md = call("RM_RaMovedD", "Conv_IntToDouble", 300, 400)
    md.pin("InInt", "in", T_INT, "0")
    md.pin("ReturnValue", "out", T_DOUBLE)
    link(mi, "ReturnValue", md, "InInt")

    # ---- charge -----------------------------------------------------------
    pursuit = n(VarGet("RM_RaPursuit", "PursuitCost", T_DOUBLE, 300, 560))
    hold = n(VarGet("RM_RaHold", "HoldCost", T_DOUBLE, 300, 640))
    hold2 = n(VarGet("RM_RaHold2", "HoldCost", T_DOUBLE, 300, 720))
    solar = n(VarGet("RM_RaSolar", "SolarRecovery", T_DOUBLE, 300, 800))
    charge = n(VarGet("RM_RaCharge", "Charge", T_DOUBLE, 300, 880))
    startc = n(VarGet("RM_RaStart", "StartCharge", T_DOUBLE, 300, 960))

    gap = call("RM_RaGap", "Subtract_DoubleDouble", 480, 580)
    gap.pin("A", "in", T_DOUBLE, "0.0")
    gap.pin("B", "in", T_DOUBLE, "0.0")
    gap.pin("ReturnValue", "out", T_DOUBLE)
    vlink(pursuit, gap, "A")
    vlink(hold, gap, "B")

    scaled = call("RM_RaScaled", "Multiply_DoubleDouble", 640, 580)
    scaled.pin("A", "in", T_DOUBLE, "0.0")
    scaled.pin("B", "in", T_DOUBLE, "0.0")
    scaled.pin("ReturnValue", "out", T_DOUBLE)
    link(gap, "ReturnValue", scaled, "A")
    link(md, "ReturnValue", scaled, "B")

    cost = call("RM_RaCost", "Add_DoubleDouble", 800, 580)
    cost.pin("A", "in", T_DOUBLE, "0.0")
    cost.pin("B", "in", T_DOUBLE, "0.0")
    cost.pin("ReturnValue", "out", T_DOUBLE)
    vlink(hold2, cost, "A")
    link(scaled, "ReturnValue", cost, "B")

    spent = call("RM_RaSpent", "Subtract_DoubleDouble", 960, 700)
    spent.pin("A", "in", T_DOUBLE, "0.0")
    spent.pin("B", "in", T_DOUBLE, "0.0")
    spent.pin("ReturnValue", "out", T_DOUBLE)
    vlink(charge, spent, "A")
    link(cost, "ReturnValue", spent, "B")

    recovered = call("RM_RaRecov", "Add_DoubleDouble", 1120, 700)
    recovered.pin("A", "in", T_DOUBLE, "0.0")
    recovered.pin("B", "in", T_DOUBLE, "0.0")
    recovered.pin("ReturnValue", "out", T_DOUBLE)
    link(spent, "ReturnValue", recovered, "A")
    vlink(solar, recovered, "B")

    clamped = call("RM_RaClamp", "FClamp", 1280, 700)
    clamped.pin("Value", "in", T_DOUBLE, "0.0")
    clamped.pin("Min", "in", T_DOUBLE, "0.0")
    clamped.pin("Max", "in", T_DOUBLE, "0.0")
    clamped.pin("ReturnValue", "out", T_DOUBLE)
    link(recovered, "ReturnValue", clamped, "Value")
    vlink(startc, clamped, "Max")

    # ---- the two writes, in an exec chain ----------------------------------
    # Deliberately the top-left of the block. UE pastes a selection so its
    # bounding box lands at the mouse, so putting the two nodes that need
    # hand-wiring furthest up-left drops them next to the entry and return
    # nodes, instead of 4000 units away at the far end of the fan-out.
    set_rex = n(VarSet("RM_RaSetRex", "RexTile", T_V2D, -3000, -1200))
    set_charge = n(VarSet("RM_RaSetCharge", "Charge", T_DOUBLE, -2750, -1200))
    for i, t in enumerate(final.pins):
        if t[0] == "ReturnValue":
            final.pins[i] = (t[:4] + (list(t[4]) + [(set_rex.name, set_rex.pid("RexTile"))],)
                             + t[5:])
    set_rex.value_links.append((final.name, final.pid("ReturnValue")))
    # Charge is written FIRST, and the order is load-bearing.
    #
    # "Did Rex move" is Manhattan(final, RexTile) > 0, and RexTile there is a
    # pure Get. UE evaluates a pure chain at the moment the impure node that
    # consumes it runs, not once up front -- so with the writes the other way
    # round, that Get ran after RexTile had already become `final`, the
    # distance was always 0, `moved` was always false, and Rex paid HoldCost
    # for a move it had just made. The self-test read 1.0 where it expected 94
    # and that is the only reason this was noticed; it compiled clean and the
    # veto assertion beside it still passed.
    #
    # Nothing in the charge chain wants the new RexTile, so doing the write
    # that invalidates the read last is enough.
    set_charge.exec_out.append((set_rex.name, set_rex.pid("execute")))
    set_rex.exec_in.append((set_charge.name, set_charge.pid("then")))
    set_charge.value_links.append((clamped.name, clamped.pid("ReturnValue")))
    for i, t in enumerate(clamped.pins):
        if t[0] == "ReturnValue":
            clamped.pins[i] = (t[:4] + (list(t[4])
                               + [(set_charge.name, set_charge.pid("Charge"))],) + t[5:])
    return nodes


def syncactors():
    """Move the three actors in the level onto the tiles the fight is using.

    Nothing in docs/UNREAL-BLUEPRINT-SPEC.md asks for this -- the spec defines
    the whole round in tile space and never says anything moves on screen. The
    acceptance test does: "the robot moves to the tile it predicted". So this
    is the join between the logic, which is finished and asserted, and the
    thing a person actually watches.

    The marker is a parameter rather than a variable because it is RexAct's
    return value, and it is the only reason the prediction is visible at all.
    Without it on screen the veto has nothing to read against and the fight
    looks like an ordinary chase.

    Actors are found with GetAllActorsOfClass and index 0 rather than held in
    variables, because ue_build_arena.py places exactly one of each and there
    is no spawn step that could hand out references. If the arena ever gets a
    second dog, this is the line that breaks.
    """
    nodes = []

    def n(node):
        nodes.append(node)
        return node

    def call(name, member, x, y, lib=MATH, pure=True):
        return n(Node(name, member, x, y, lib=lib, pure=pure))

    def link(a, apin, b, bpin):
        for node, pinname, other, otherpin in ((a, apin, b, bpin), (b, bpin, a, apin)):
            for i, t in enumerate(node.pins):
                if t[0] == pinname:
                    node.pins[i] = (t[:4] + (list(t[4]) + [(other.name, other.pid(otherpin))],)
                                    + t[5:])
                    break

    prev_exec = None          # the node whose `then` feeds the next one
    marker_links = []

    #  asset, where the tile comes from
    TARGETS = [("BP_Dog", "DogTile"), ("BP_Rex", "RexTile"), ("BP_Marker", None)]
    for i, (asset, var) in enumerate(TARGETS):
        row = -400 + i * 260
        find = n(GetAllActors("RM_SyFind%d" % i, asset, -1400, row))
        item = n(ArrayGet("RM_SyItem%d" % i, -1150, row + 60, elem_cat=T_ACTOR))
        item.array_links.append((find.name, find.pid("OutActors")))
        find.out_links.append((item.name, item.pid("Array")))

        tw = call("RM_SyTw%d" % i, "TileToWorld", -900, row + 120, lib=SELF_CTX)
        tw.pin("Tile", "in", T_V2D)
        tw.pin("World", "out", T_VEC)
        if var:
            src = n(VarGet("RM_SyVar%d" % i, var, T_V2D, -1150, row + 160))
            src.links.append((tw.name, tw.pid("Tile")))
            tw.pins[0] = tw.pins[0][:4] + ([(src.name, src.out_pin())],) + tw.pins[0][5:]
        else:
            marker_links.append((tw.name, tw.pid("Tile")))

        move = n(MemberCall("RM_SyMove%d" % i, "K2_SetActorLocation", ACTOR_CLS, -650, row))
        move.pin("execute", "in", T_EXEC)
        move.pin("then", "out", T_EXEC)
        move.pin("NewLocation", "in", T_VEC)
        move.pin("bSweep", "in", T_BOOL, "false")
        move.pin("SweepHitResult", "out",
                 'PinType.PinCategory="struct",PinType.PinSubCategory="",'
                 'PinType.PinSubCategoryObject='
                 '"/Script/CoreUObject.ScriptStruct\'/Script/Engine.HitResult\'"')
        move.pin("bTeleport", "in", T_BOOL, "true")
        move.pin("ReturnValue", "out", T_BOOL)
        move.self_links.append((item.name, item.pid("Output")))
        item.out_links.append((move.name, move.pid("self")))
        link(tw, "World", move, "NewLocation")

        # exec: find -> move -> next find
        find.exec_out.append((move.name, move.pid("execute")))
        move.pins[0] = move.pins[0][:4] + ([(find.name, find.pid("then"))],) + move.pins[0][5:]
        if prev_exec is not None:
            prev_exec.pins[1] = (prev_exec.pins[1][:4]
                                 + ([(find.name, find.pid("execute"))],)
                                 + prev_exec.pins[1][5:])
            find.exec_in.append((prev_exec.name, prev_exec.pid("then")))
        prev_exec = move
    return nodes


def beginplay():
    """BP_FightManager's EventGraph: set the fight up and show it.

    Every constant this copies from is already a variable on the Blueprint and
    already asserted, so nothing here is a new number -- DogSpawn (0,0),
    RexSpawn (5,5), StartCharge 100, StartStamina 15. The point is that the
    round loop and the level stop being two separate things: after this runs,
    what is on screen is what the logic thinks is true.

    It ends on SyncActors so the marker starts under Rex rather than at the
    world origin, which is where an unplaced actor sits and looks like a bug.

    Pasted into the EventGraph whole. The BeginPlay node is inside the paste,
    so unlike every function graph here this one needs no hand-wiring at all.
    """
    nodes = []
    begin = EventNode("RM_BpBegin", "ReceiveBeginPlay", -1200, -400)
    begin.pin("then", "out", T_EXEC)
    nodes.append(begin)

    #  target variable, source variable or literal, pin type
    STEPS = [
        ("DogTile", "DogSpawn", T_V2D, None),
        ("RexTile", "RexSpawn", T_V2D, None),
        ("Charge", "StartCharge", T_DOUBLE, None),
        ("Stamina", "StartStamina", T_INT, None),
        ("Round", None, T_INT, "0"),
        ("PhaseIndex", None, T_INT, "0"),
    ]
    prev = begin
    prev_pin = "then"
    for i, (target, source, typefrag, literal) in enumerate(STEPS):
        x = -1000 + i * 260
        setter = VarSet("RM_Bp%s" % target, target, typefrag, x, -400,
                        value_default=literal)
        nodes.append(setter)
        if source is not None:
            get = VarGet("RM_BpGet%s" % source, source, typefrag, x - 40, -260)
            get.links.append((setter.name, setter.pid(target)))
            setter.value_links.append((get.name, get.out_pin()))
            nodes.append(get)
        setter.exec_in.append((prev.name, prev.pid(prev_pin)))
        if prev is begin:
            begin.pins[0] = begin.pins[0][:4] + ([(setter.name, setter.pid("execute"))],) \
                + begin.pins[0][5:]
        else:
            prev.exec_out.append((setter.name, setter.pid("execute")))
        prev, prev_pin = setter, "then"

    # ---- put the actors where the state says they are ----------------------
    rex = VarGet("RM_BpSyncRex", "RexTile", T_V2D, 620, -260)
    sync = Node("RM_BpSync", "SyncActors", 620, -400, lib=SELF_CTX, pure=False)
    sync.pin("execute", "in", T_EXEC)
    sync.pin("then", "out", T_EXEC)
    sync.pin("Marker", "in", T_V2D, None, [(rex.name, rex.out_pin())])
    rex.links.append((sync.name, sync.pid("Marker")))
    sync.pins[0] = sync.pins[0][:4] + ([(prev.name, prev.pid("then"))],) + sync.pins[0][5:]
    prev.exec_out.append((sync.name, sync.pid("execute")))
    nodes.extend([rex, sync])
    return nodes


def onplayermove():
    """OnPlayerMove(Direction) -- one round, from GDD 6.1's numbered list.

    Step 1 is the one that is easy to get wrong and is a bug fix, not a
    feature: a move into the fence prints "The fence is there. Nothing on that
    side." and returns **without consuming the round**. qa/adversary.js finding
    RM-003 was that a rejected move gave the player no feedback at all, so they
    could not tell a refused input from a dropped one. That is the only reason
    there is a Branch in this graph.

    "wait" needs no special case. Its offset is (0,0), so the target tile is
    the tile the dog is already on, InBounds is true, and the round proceeds
    with the dog not moving -- which is exactly what waiting is. GDD 3 counts
    it in the move history, so it still gets appended to Moves and still feeds
    stall_detected later.

    Step 5's clamp is RM-002: without Max(0, ...) stamina reached -1 and the
    HUD showed it.

    SpeakRead, CheckGate and CheckEnd are not called yet -- they are not built.
    The round advances, Rex acts, and the actors move; nothing is said and
    nothing ends. That is the honest state of it.

    Two wires by hand: the entry exec into the Branch, and the entry's
    Direction into RM_OmDir. Everything else that wants Direction reads
    RM_OmDir's output instead, so the fan-out happens inside the pasted set
    where the text carries it. Links to a node outside the clipboard are
    dropped on paste (FEdGraphUtilities::PostProcessPastedNodePinLinks breaks
    "links across the selection set"), so wires to the entry node cannot be
    generated and every one of them has to be dragged.

    RM_OmDir is ToLower, which is a real normalisation and not a stand-in for
    a reroute: it means a direction that arrives capitalised still matches.
    """
    nodes = []
    DIRS = ["left", "right", "up", "down"]

    def n(node):
        nodes.append(node)
        return node

    def call(name, member, x, y, lib=MATH, pure=True):
        return n(Node(name, member, x, y, lib=lib, pure=pure))

    def link(a, apin, b, bpin):
        for node, pinname, other, otherpin in ((a, apin, b, bpin), (b, bpin, a, apin)):
            for i, t in enumerate(node.pins):
                if t[0] == pinname:
                    node.pins[i] = (t[:4] + (list(t[4]) + [(other.name, other.pid(otherpin))],)
                                    + t[5:])
                    break

    def vlink(vnode, b, bpin):
        vnode.links.append((b.name, b.pid(bpin)))
        for i, t in enumerate(b.pins):
            if t[0] == bpin:
                b.pins[i] = (t[:4] + (list(t[4]) + [(vnode.name, vnode.out_pin())],) + t[5:])
                break

    # ---- Direction -> offset ------------------------------------------------
    # The single point the entry node's Direction pin has to reach. Placed
    # beside the Branch so both hand wires end within one screen of each other.
    dirn = call("RM_OmDir", "ToLower", -1650, -1000, lib=STR)
    dirn.pin("SourceString", "in", T_STR)
    dirn.pin("ReturnValue", "out", T_STR)

    ints = {}
    for i, d in enumerate(DIRS):
        eq = call("RM_OmEq%s" % d[:1].upper(), "EqualEqual_StrStr", -3000, -900 + i * 120, lib=STR)
        eq.pin("A", "in", T_STR)
        link(dirn, "ReturnValue", eq, "A")
        eq.pin("B", "in", T_STR, d)
        eq.pin("ReturnValue", "out", T_BOOL)
        b2i = call("RM_OmI%s" % d[:1].upper(), "Conv_BoolToInt", -2800, -900 + i * 120)
        b2i.pin("InBool", "in", T_BOOL, "false")
        b2i.pin("ReturnValue", "out", T_INT)
        link(eq, "ReturnValue", b2i, "InBool")
        ints[d] = b2i

    offs = {}
    for axis, plus, minus, row in (("X", "right", "left", -900), ("Y", "down", "up", -760)):
        sub = call("RM_OmOff%s" % axis, "Subtract_IntInt", -2600, row)
        sub.pin("A", "in", T_INT, "0")
        sub.pin("B", "in", T_INT, "0")
        sub.pin("ReturnValue", "out", T_INT)
        link(ints[plus], "ReturnValue", sub, "A")
        link(ints[minus], "ReturnValue", sub, "B")
        cv = call("RM_OmD%s" % axis, "Conv_IntToDouble", -2450, row)
        cv.pin("InInt", "in", T_INT, "0")
        cv.pin("ReturnValue", "out", T_DOUBLE)
        link(sub, "ReturnValue", cv, "InInt")
        offs[axis] = cv

    # ---- target tile --------------------------------------------------------
    dog = n(VarGet("RM_OmDog", "DogTile", T_V2D, -2450, -600))
    br = call("RM_OmBr", "BreakVector2D", -2300, -600)
    br.pin("InVec", "in", T_V2D)
    br.pin("X", "out", T_DOUBLE, "0.0")
