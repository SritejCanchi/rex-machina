def speakread():
    """SpeakRead -- the robot names something it measured off your movement.

    The other half of the One Wow. GDD 4: every trigger that fires this round,
    in priority order; take the first that is not the category spoken last
    round and whose line has not already been used this run. A5 returned only
    the first firing category, one category dominated, suppression ate the
    rest, and a winning run surfaced two lines out of twenty-four -- so the
    fall-through is the point, not a detail.

    Tier 0 is the four cheap triggers, which reach 12 of the 24 lines.
    `periodicity_called` needs Periodicity; `cover_habit` and `exit_fixation`
    need the phase tile arrays parsed. Those are Tier 1.

    Three things the data allows, each of which removes a lot of graph. All
    three are written up in docs/UNREAL-SPEECH-PLAN.md.

    **The row lookup is arithmetic.** DT_NemesisReads is eight categories by
    three bands in a fixed order, so the row is `band * 8 + category`. And
    GetDataTableColumnAsString hands back the whole `Line` column as a plain
    string array, so the read is Array_Get on that -- no GetDataTableRow node,
    no struct pin, no BreakStruct whose pin names would have been GUID-
    suffixed and unguessable.

    **The counts need no loop.** FreqSpan is 20 and MaxRounds is 15, so
    "the last twenty moves" is always the whole Moves array and nothing has to
    be sliced. Joining it and measuring what disappears when a word is removed
    counts that word:

        count(d) = (Len(joined) - Len(Replace(joined, d, ""))) / Len(d)

    None of left/right/up/down is a substring of another and "wait" contains
    none of them, so the four counts are exact. Forty nodes instead of four
    hundred unrolled. This is why CheckEnd had to land first: it is what keeps
    Moves under twenty.

    **The direction guard is one comparison.** qa/adversary.js finding RM-001:
    the sealing_direction lines all name "left" but the trigger fires whenever
    any direction dominates, so the robot told a right-running dog it favoured
    left. Checked against all 24 rows, only sealing_direction names a
    direction and all three say "left", so game.js's regex reduces to "the
    dominant direction is left". Data-shaped: regenerate the reads with other
    directions and this has to become general again.

    Ties go to the earliest compass direction because game.js scans
    left,right,up,down with a strict `>`, which is the same as "left wins when
    its count equals the maximum".
    """
    #  name, table index, word length for the count trick
    DIRS = [("left", 4), ("right", 5), ("up", 2), ("down", 4)]
    #  label, table index -- in game.js's priority order
    CATS = ["seal", "stall", "strain", "gait"]
    CAT_INDEX = {"seal": 0, "stall": 4, "strain": 6, "gait": 5}

    nodes = []

    def n(node):
        nodes.append(node)
        return node

    def call(name, member, x, y, lib=MATH, pure=True):
        return n(Node(name, member, x, y, lib=lib, pure=pure))

    def link(a, apin, b, bpin):
        for node, pinname, other, otherpin in ((a, apin, b, bpin), (b, bpin, a, apin)):
            for i, t in enumerate(node.pins):
                if t[0] == pinname:
                    node.pins[i] = (t[:4] + (list(t[4]) + [(other.name, other.pid(otherpin))],)
                                    + t[5:])
                    break

    def vlink(vnode, b, bpin):
        vnode.links.append((b.name, b.pid(bpin)))
        for i, t in enumerate(b.pins):
            if t[0] == bpin:
                b.pins[i] = (t[:4] + (list(t[4]) + [(vnode.name, vnode.out_pin())],) + t[5:])
                break

    def i2(name, member, x, y, a_def="0", b_def="0"):
        """A two-input integer node."""
        node = call(name, member, x, y)
        node.pin("A", "in", T_INT, a_def)
        node.pin("B", "in", T_INT, b_def)
        node.pin("ReturnValue", "out", T_INT)
        return node

    def bool2(name, member, x, y):
        node = call(name, member, x, y)
        node.pin("A", "in", T_BOOL, "false")
        node.pin("B", "in", T_BOOL, "false")
        node.pin("ReturnValue", "out", T_BOOL)
        return node

    def notb(name, x, y, src):
        node = call(name, "Not_PreBool", x, y)
        node.pin("A", "in", T_BOOL, "false")
        node.pin("ReturnValue", "out", T_BOOL)
        link(src, "ReturnValue", node, "A")
        return node

    def b2i(name, x, y, src):
        node = call(name, "Conv_BoolToInt", x, y)
        node.pin("InBool", "in", T_BOOL, "false")
        node.pin("ReturnValue", "out", T_INT)
        link(src, "ReturnValue", node, "InBool")
        return node

    STR_ELEM = T_STRING_ELEM

    # ---- the Line column, as a plain string array --------------------------
    col = call("RM_SrCol", "GetDataTableColumnAsString", -3200, -1400,
               lib=DTLIB, pure=False)
    col.pin("execute", "in", T_EXEC)
    col.pin("then", "out", T_EXEC)
    col.pin("DataTable", "in", T_DATATABLE,
            "/Game/Data/DT_NemesisReads.DT_NemesisReads")
    col.pin("PropertyName", "in", T_NAME, "Line")
    col.pin("ReturnValue", "out", STR_ELEM, None, (), TAIL_ARRAY)

    # ---- direction counts, straight off one joined string ------------------
    moves = n(VarGet("RM_SrMoves", "Moves", STR_ELEM, -3000, -1100, tail=TAIL_ARRAY))
    join = call("RM_SrJoin", "JoinStringArray", -2820, -1100, lib=STR)
    join.pin("SourceArray", "in", STR_ELEM, None, (), TAIL_ARRAY_REF)
    join.pin("Separator", "in", T_STR, ",")
    join.pin("ReturnValue", "out", T_STR)
    vlink(moves, join, "SourceArray")

    len_all = call("RM_SrLenAll", "Len", -2650, -1100, lib=STR)
    len_all.pin("S", "in", T_STR)
    len_all.pin("ReturnValue", "out", T_INT)
    link(join, "ReturnValue", len_all, "S")

    counts = {}
    for i, (d, wl) in enumerate(DIRS):
        D = d[:1].upper()
        row = -1000 + i * 130
        rep = call("RM_SrRep" + D, "Replace", -2500, row, lib=STR)
        rep.pin("SourceString", "in", T_STR)
        rep.pin("From", "in", T_STR, d)
        rep.pin("To", "in", T_STR)
        rep.pin("ReturnValue", "out", T_STR)
        link(join, "ReturnValue", rep, "SourceString")

        ln = call("RM_SrLen" + D, "Len", -2340, row, lib=STR)
        ln.pin("S", "in", T_STR)
        ln.pin("ReturnValue", "out", T_INT)
        link(rep, "ReturnValue", ln, "S")

        diff = i2("RM_SrDiff" + D, "Subtract_IntInt", -2180, row)
        link(len_all, "ReturnValue", diff, "A")
        link(ln, "ReturnValue", diff, "B")

        cnt = i2("RM_SrCnt" + D, "Divide_IntInt", -2020, row, b_def=str(wl))
        link(diff, "ReturnValue", cnt, "A")
        counts[d] = cnt

    lr = i2("RM_SrNLR", "Add_IntInt", -1860, -1000)
