def piecemotion(rest_z=5.0):
    """Event Tick on a piece: let the mesh catch up to the actor it belongs to.

    The round loop teleports. SyncActors reads DogTile, RexTile and the
    predicted tile and calls SetActorLocation, and a tile is 200cm, so every
    move is an instant two-metre jump. The fight is legible that way and it
    looks like a spreadsheet.

    This does not change the logic by one node. The *actor* still teleports --
    every distance, every InBounds test, every Manhattan call is unchanged --
    and only the mesh component lags behind and eases in. Movement becomes
    something you watch instead of something you infer, and Rex arriving reads
    as a lunge, because it covers the same distance in the same time whether
    the tile is next door or across the board.

    Doing it the other way round, interpolating the actor and letting the
    logic read the interpolated position, would have made Manhattan return
    fractions mid-slide and the veto fire on a tile nobody was standing on.

    `rest_z` is the mesh's own height above the actor origin, which is 5 for
    the three pieces and 7 for the marker so it clears the tile it sits on.
    The whole graph pastes with no hand wiring at all: the Tick event is
    inside it.
    """
    nodes = []

    def n(node):
        nodes.append(node)
        return node

    tick = n(EventNode("RM_MoTick", "ReceiveTick", -1300, -300))

    mesh = n(VarGet("RM_MoMesh", "Mesh", T_SMC, -1300, -80))

    cur = n(MemberCall("RM_MoCur", "K2_GetComponentLocation", SCENE_COMP,
                       -1050, -80, pure=True, self_type=T_SMC))
    cur.pin("ReturnValue", "out", T_VEC)
    cur.self_links.append((mesh.name, mesh.out_pin()))
    mesh.links.append((cur.name, cur.pid("self")))

    here = n(Node("RM_MoHere", "K2_GetActorLocation", -1050, 60, lib=SELF_CTX))
    here.pin("ReturnValue", "out", T_VEC)

    off = n(Node("RM_MoOff", "MakeVector", -1050, 200))
    off.pin("X", "in", T_DOUBLE, "0.0")
    off.pin("Y", "in", T_DOUBLE, "0.0")
    off.pin("Z", "in", T_DOUBLE, "%.6f" % rest_z)
    off.pin("ReturnValue", "out", T_VEC)

    lift = n(Node("RM_MoLift", "Add_VectorVector", -850, 60))
    lift.pin("A", "in", T_VEC)
    lift.pin("B", "in", T_VEC)
    lift.pin("ReturnValue", "out", T_VEC)

    def link(a, apin, b, bpin):
        for node, pinname, other, otherpin in ((a, apin, b, bpin), (b, bpin, a, apin)):
            for i, t in enumerate(node.pins):
                if t[0] == pinname:
                    node.pins[i] = (t[:4] + (list(t[4]) + [(other.name, other.pid(otherpin))],)
                                    + t[5:])
                    break

    link(here, "ReturnValue", lift, "A")
    link(off, "ReturnValue", lift, "B")

    ease = n(Node("RM_MoEase", "VInterpTo", -650, -80))
    ease.pin("Current", "in", T_VEC)
    ease.pin("Target", "in", T_VEC)
    ease.pin("DeltaTime", "in", T_DOUBLE, "0.0")
    # 9 is about a sixth of a second to cover a tile: fast enough that the next
    # key press never queues behind it, slow enough to see which way it went.
    ease.pin("InterpSpeed", "in", T_DOUBLE, "9.0")
    ease.pin("ReturnValue", "out", T_VEC)
    link(cur, "ReturnValue", ease, "Current")
    link(lift, "ReturnValue", ease, "Target")

    # Tick's DeltaSeconds is a C++ float and this pin is a Blueprint double.
    # The reconstruct on paste rewrites the type and keeps the link, because
    # links are matched by pin name.
    tick.pin("DeltaSeconds", "out", T_DOUBLE, None,
             [(ease.name, ease.pid("DeltaTime"))])
    for i, t in enumerate(ease.pins):
        if t[0] == "DeltaTime":
            ease.pins[i] = t[:4] + ([(tick.name, tick.pid("DeltaSeconds"))],) + t[5:]

    put = n(MemberCall("RM_MoPut", "K2_SetWorldLocation", SCENE_COMP,
                       -420, -300, self_type=T_SMC))
    put.pin("execute", "in", T_EXEC, None, [(tick.name, tick.pid("then"))])
    put.pin("then", "out", T_EXEC)
    put.pin("NewLocation", "in", T_VEC, None, [(ease.name, ease.pid("ReturnValue"))])
    put.pin("bSweep", "in", T_BOOL, "false")
    put.pin("bTeleport", "in", T_BOOL, "true")
    # SweepHitResult is deliberately not declared. It is an out struct whose
    # exact type text is easy to get wrong, and the reconstruct on paste adds
    # any pin the function has that the text left out.
    put.self_links.append((mesh.name, mesh.out_pin()))
    mesh.links.append((put.name, put.pid("self")))
    for i, t in enumerate(ease.pins):
        if t[0] == "ReturnValue":
            ease.pins[i] = (t[:4] + (list(t[4]) + [(put.name, put.pid("NewLocation"))],)
                            + t[5:])
    tick.pin("then", "out", T_EXEC, None, [(put.name, put.pid("execute"))])
    return nodes


def fighthud():
    """BP_FightHUD's EventGraph: charge, round, stamina, and what Rex just said.

    Four numbers and one sentence, and the sentence is the point. Everything
    else on screen exists to make the read land: you see the charge fall, you
    see the band it falls into, and then the robot names something you did.
    Without the bar the reads arrive out of nowhere; without the reads the bar
    is a bar.

    The manager is found by GetAllActorsOfClass and cast, every frame. That is
    a full actor iteration per draw and it is not free, but the level holds
    about a hundred and seventy actors and the alternative -- caching it in a
    HUD variable behind an IsValid branch -- is six more nodes guarding
    against a cost that does not exist at this size.

    Nothing here writes. The HUD reads the fight and draws it; if this whole
    Blueprint were deleted the fight would still play, which is the property
    that keeps a HUD from quietly becoming game logic.
    """
    ASSET = "BP_FightManager"
    nodes = []

    def n(node):
        nodes.append(node)
        return node

    def call(name, member, x, y, lib=MATH, pure=True):
        return n(Node(name, member, x, y, lib=lib, pure=pure))

    def link(a, apin, b, bpin):
        for node, pinname, other, otherpin in ((a, apin, b, bpin), (b, bpin, a, apin)):
            for i, t in enumerate(node.pins):
                if t[0] == pinname:
                    node.pins[i] = (t[:4] + (list(t[4]) + [(other.name, other.pid(otherpin))],)
                                    + t[5:])
                    break

    # ---- find the fight ----------------------------------------------------
    hud = n(EventNode("RM_HdDraw", "ReceiveDrawHUD", -2400, -600, parent=HUD_CLASS))
    hud.pin("then", "out", T_EXEC)
    hud.pin("SizeX", "out", T_INT)
    hud.pin("SizeY", "out", T_INT)

    # No cast. GetAllActorsOfClass types its output array from the class pin,
    # so the element already is a BP_FightManager -- the compiler says so, in
    # as many words, if you put a cast in anyway.
    MGR = ('PinType.PinCategory="object",PinType.PinSubCategory="",'
           'PinType.PinSubCategoryObject="%s"' % bp_class_ref(ASSET))
    findall = n(GetAllActors("RM_HdAll", ASSET, -2400, -600, elem=MGR))
    findall.exec_in.append((hud.name, hud.pid("then")))
    for i, t in enumerate(hud.pins):
        if t[0] == "then":
            hud.pins[i] = t[:4] + ([(findall.name, findall.pid("execute"))],) + t[5:]

    first = n(ArrayGet("RM_HdFirst", -2150, -380, elem_cat=MGR))
    first.array_links.append((findall.name, findall.pid("OutActors")))
    findall.out_links.append((first.name, first.pid("Array")))

    def read(tag, var, typefrag, x, y):
        """One variable off the manager the array handed back."""
        g = n(OtherVarGet("RM_Hd" + tag, ASSET, var, typefrag, x, y))
        g.self_links.append((first.name, first.pid("Output")))
        first.out_links.append((g.name, g.pid("self")))
        return g

    charge = read("Charge", "Charge", T_DOUBLE, -1700, -200)
    stam = read("Stam", "Stamina", T_INT, -1700, -80)
    rnd = read("Round", "Round", T_INT, -1700, 40)
    maxr = read("Max", "MaxRounds", T_INT, -1700, 160)
    said = read("Said", "PendingLine", T_STR, -1700, 280)

    def vlink(vnode, b, bpin):
        vnode.links.append((b.name, b.pid(bpin)))
        for i, t in enumerate(b.pins):
            if t[0] == bpin:
                b.pins[i] = (t[:4] + (list(t[4]) + [(vnode.name, vnode.out_pin())],) + t[5:])
                break

    # ---- the strings -------------------------------------------------------
    def joins(tag, parts, x, y):
        """Concat a list of (literal or (node, pin)) into one string."""
        prev = None
        for i, part in enumerate(parts):
            c = call("RM_HdJ%s%d" % (tag, i), "Concat_StrStr", x + i * 150, y, lib=STR)
            c.pin("A", "in", T_STR, None if prev else (part if isinstance(part, str) else None))
            c.pin("B", "in", T_STR)
            c.pin("ReturnValue", "out", T_STR)
            if prev is not None:
                link(prev, "ReturnValue", c, "A")
            if isinstance(part, str):
                if prev is not None:
                    c.pins[1] = ("B", "in", T_STR, part, [], None)
            else:
                link(part[0], part[1], c, "B")
            prev = c
        return prev

    # charge, rounded, because a double prints as 94.000000
    chint = call("RM_HdChInt", "Round", -1500, -200)
    chint.pin("A", "in", T_DOUBLE, "0.0")
    chint.pin("ReturnValue", "out", T_INT)
    vlink(charge, chint, "A")
    chstr = call("RM_HdChStr", "Conv_IntToString", -1350, -200, lib=STR)
    chstr.pin("InInt", "in", T_INT, "0")
    chstr.pin("ReturnValue", "out", T_STR)
    link(chint, "ReturnValue", chstr, "InInt")

    stamstr = call("RM_HdStStr", "Conv_IntToString", -1350, -80, lib=STR)
    stamstr.pin("InInt", "in", T_INT, "0")
    stamstr.pin("ReturnValue", "out", T_STR)
    vlink(stam, stamstr, "InInt")

    rndstr = call("RM_HdRnStr", "Conv_IntToString", -1350, 40, lib=STR)
    rndstr.pin("InInt", "in", T_INT, "0")
    rndstr.pin("ReturnValue", "out", T_STR)
    vlink(rnd, rndstr, "InInt")

    maxstr = call("RM_HdMxStr", "Conv_IntToString", -1350, 160, lib=STR)
    maxstr.pin("InInt", "in", T_INT, "0")
    maxstr.pin("ReturnValue", "out", T_STR)
    vlink(maxr, maxstr, "InInt")

    line_charge = joins("C", ["CHARGE  ", (chstr, "ReturnValue")], -1150, -260)
    line_stam = joins("S", ["STAMINA  ", (stamstr, "ReturnValue")], -1150, -100)
    line_round = joins("R", ["ROUND  ", (rndstr, "ReturnValue"), "  /  ",
                             (maxstr, "ReturnValue")], -1150, 60)

    # ---- the bar -----------------------------------------------------------
    # Charge is 0..100 and the bar is 360 wide, so the fill is Charge * 3.6.
    fill = call("RM_HdFill", "Multiply_DoubleDouble", -1500, -320)
    fill.pin("A", "in", T_DOUBLE, "0.0")
    fill.pin("B", "in", T_DOUBLE, "3.6")
    fill.pin("ReturnValue", "out", T_DOUBLE)
    vlink(charge, fill, "A")

    # The read sits near the bottom of whatever window this is, so it follows
    # SizeY rather than a pixel that only happens to be right at one size.
    sizey = call("RM_HdSizeY", "Conv_IntToDouble", -1500, 400)
    sizey.pin("InInt", "in", T_INT, "0")
    sizey.pin("ReturnValue", "out", T_DOUBLE)
    for i, t in enumerate(hud.pins):
        if t[0] == "SizeY":
            hud.pins[i] = t[:4] + ([(sizey.name, sizey.pid("InInt"))],) + t[5:]
    sizey.pins[0] = sizey.pins[0][:4] + ([(hud.name, hud.pid("SizeY"))],) + sizey.pins[0][5:]
    lowy = call("RM_HdLowY", "Multiply_DoubleDouble", -1350, 400)
    lowy.pin("A", "in", T_DOUBLE, "0.0")
    lowy.pin("B", "in", T_DOUBLE, "0.86")
    lowy.pin("ReturnValue", "out", T_DOUBLE)
    link(sizey, "ReturnValue", lowy, "InInt" if False else "A")

    # ---- draw --------------------------------------------------------------
    chain = [findall]

    def after(node, in_pin="execute"):
        prev = chain[-1]
        if isinstance(prev, GetAllActors):
            prev.exec_out.append((node.name, node.pid(in_pin)))
            src = (prev.name, prev.pid("then"))
        else:
            for i, t in enumerate(prev.pins):
                if t[0] == "then":
                    prev.pins[i] = (t[:4] + (list(t[4]) + [(node.name, node.pid(in_pin))],)
                                    + t[5:])
                    break
            src = (prev.name, prev.pid("then"))
        for i, t in enumerate(node.pins):
            if t[0] == in_pin:
                node.pins[i] = t[:4] + ([src],) + t[5:]
                break
        chain.append(node)
        return node

    def rect(tag, colour, x, y, w, h, w_link=None):
        r = call("RM_HdR" + tag, "DrawRect", 0, 0, lib=SELF_CTX, pure=False)
        r.pin("execute", "in", T_EXEC)
        r.pin("then", "out", T_EXEC)
        r.pin("RectColor", "in", T_LINCOLOR, colour)
        r.pin("ScreenX", "in", T_FLOAT, "%.1f" % x)
        r.pin("ScreenY", "in", T_FLOAT, "%.1f" % y)
        r.pin("ScreenW", "in", T_FLOAT, "%.1f" % w)
        r.pin("ScreenH", "in", T_FLOAT, "%.1f" % h)
        after(r)
        if w_link is not None:
            link(w_link[0], w_link[1], r, "ScreenW")
        return r

    def text(tag, colour, x, y, scale, literal=None, src=None, y_link=None):
        t = call("RM_HdT" + tag, "DrawText", 0, 0, lib=SELF_CTX, pure=False)
        t.pin("execute", "in", T_EXEC)
        t.pin("then", "out", T_EXEC)
        t.pin("Text", "in", T_STR, literal)
        t.pin("TextColor", "in", T_LINCOLOR, colour)
        t.pin("ScreenX", "in", T_FLOAT, "%.1f" % x)
        t.pin("ScreenY", "in", T_FLOAT, "%.1f" % y)
        t.pin("Scale", "in", T_FLOAT, "%.2f" % scale)
        after(t)
        if src is not None:
            # OtherVarGet keeps its links in a list rather than a pins table,
            # so it goes through vlink; everything else through link.
            if isinstance(src[0], OtherVarGet):
                vlink(src[0], t, "Text")
            else:
                link(src[0], src[1], t, "Text")
        if y_link is not None:
            link(y_link[0], y_link[1], t, "ScreenY")
        return t

    DIM = "(R=0.02,G=0.02,B=0.03,A=0.72)"
    WARM = "(R=1.0,G=0.62,B=0.22,A=1.0)"
    PALE = "(R=0.92,G=0.90,B=0.86,A=1.0)"
    CYAN = "(R=0.35,G=0.85,B=1.0,A=1.0)"

    rect("Panel", DIM, 32.0, 28.0, 380.0, 132.0)
    rect("BarBg", "(R=0.10,G=0.09,B=0.08,A=1.0)", 46.0, 44.0, 352.0, 22.0)
    rect("BarFill", WARM, 46.0, 44.0, 0.0, 22.0, w_link=(fill, "ReturnValue"))
    text("Charge", PALE, 46.0, 72.0, 1.15, src=(line_charge, "ReturnValue"))
    text("Stam", PALE, 46.0, 100.0, 1.15, src=(line_stam, "ReturnValue"))
    text("Round", PALE, 46.0, 128.0, 1.15, src=(line_round, "ReturnValue"))
    # The read, last and lowest, in Rex's own colour -- drawn twice, a dark
    # copy two pixels right and then the cyan one over it. The line lands on
    # whatever the floods are lighting at that moment, and cyan on a sodium
    # floor is the one combination that disappears.
    text("SaidShadow", "(R=0.0,G=0.0,B=0.0,A=0.85)", 48.0, 0.0, 1.5,
         src=(said, "PendingLine"), y_link=(lowy, "ReturnValue"))
    text("Said", CYAN, 46.0, 0.0, 1.5, src=(said, "PendingLine"),
         y_link=(lowy, "ReturnValue"))
    return nodes


MANHATTAN_GUID = "ED02AD0F4DA7F45E772004BAD7F4BC10"


def selftest():
    """BP_SelfTest's EventGraph: run the maths and print what it actually got.

    A Blueprint graph cannot be read back and checked, so this checks behaviour
    instead. It deliberately prints the computed value next to the expected one
    rather than asserting internally -- a PASS/FAIL boolean would hide *what*
    was wrong, and the values are what caught the Band literals reverting to
    zero.

    Boundary cases matter more than the middle of each range: Band(60) and
    Band(30) sit exactly on the spec's thresholds, where a > that should be >=
    would slip through unnoticed.

    One boundary wire to add by hand: Event BeginPlay -> RM_P0.execute.
    """
    begin = EventNode("RM_BeginPlay", "ReceiveBeginPlay", -1150, -700)
    nodes, prev_print, y = [begin], None, -600

    def y_of():
        return y

    def print_line(tag, label, value_node, value_pin):
        """label + value -> Print String, chained onto the previous print."""
        nonlocal prev_print, y
        cat = Node("RM_Cat" + tag, "Concat_StrStr", -200, y, lib=STR)
        pr = Node("RM_P" + tag, "PrintString", 120, y, lib=SYS)
        cat.pin("A", "in", T_STR, label)
        cat.pin("B", "in", T_STR, None, [(value_node.name, value_node.pid(value_pin))])
        cat.pin("ReturnValue", "out", T_STR, None, [(pr.name, pr.pid("InString"))])
        head = prev_print if prev_print is not None else begin
        pr.pin("execute", "in", T_EXEC, None, [(head.name, head.pid("then"))])
        pr.pin("then", "out", T_EXEC)
        pr.pin("InString", "in", T_STR, None, [(cat.name, cat.pid("ReturnValue"))])
        # exec links are two-way, so name this end on the upstream node too
        if prev_print is None:
            begin.pin("then", "out", T_EXEC, None, [(pr.name, pr.pid("execute"))])
        else:
            for i, t in enumerate(prev_print.pins):
                if t[0] == "then":
                    prev_print.pins[i] = (t[:4] + ([(pr.name, pr.pid("execute"))],)
                                          + t[5:])
        nodes.extend([cat, pr])
        prev_print = pr
        y += 200

    def chain(node, in_pin="execute"):
        """Hook an exec node onto the end of the chain and make it the new end.

        Node keeps its exec links in `pins`; VarSet, ArrayAdd and the rest keep
        them in `exec_in`/`exec_out` lists. Both ends of every exec wire have to
        name the other, so this writes two links, not one.
        """
        nonlocal prev_print
        head = prev_print if prev_print is not None else begin
        if hasattr(node, "exec_in"):
            node.exec_in.append((head.name, head.pid("then")))
        else:
            for i, t in enumerate(node.pins):
                if t[0] == in_pin:
                    node.pins[i] = t[:4] + ([(head.name, head.pid("then"))],) + t[5:]
                    break
        if prev_print is None:
            begin.pin("then", "out", T_EXEC, None, [(node.name, node.pid(in_pin))])
        elif hasattr(head, "exec_out"):
            head.exec_out.append((node.name, node.pid(in_pin)))
        else:
            for i, t in enumerate(head.pins):
                if t[0] == "then":
                    head.pins[i] = t[:4] + ([(node.name, node.pid(in_pin))],) + t[5:]
                    break
        nodes.append(node)
        prev_print = node
        return node

    def clear_var(tag, var, x):
        """Empty an array variable, the only way UE accepts. See ArrayClear."""
        g = VarGet("RM_%sG" % tag, var, T_STRING_ELEM, x, y_of() + 200,
                   tail=TAIL_ARRAY)
        nodes.append(g)
        c = ArrayClear("RM_%s" % tag, x, y_of())
        c.array_links.append((g.name, g.out_pin()))
        g.links.append((c.name, c.pid("TargetArray")))
        return chain(c)

    def set_var(tag, var, typefrag, literal, x, tail=None):
        """A Set node carrying a literal on its value pin.

        A Set whose value pin is left empty writes that pin's own default,
        which for an array pin is an empty array. That is how Moves and
        SpokenLines get cleared without an Array_Clear node.
        """
        return chain(VarSet("RM_%s" % tag, var, typefrag, x, y_of(),
                            value_default=literal, tail=tail))

    def manhattan_case(tag, ax, ay, bx, by, expect):
        va = Node("RM_VA" + tag, "MakeVector2D", -900, y, lib=MATH)
        vb = Node("RM_VB" + tag, "MakeVector2D", -900, y + 90, lib=MATH)
        mn = Node("RM_MN" + tag, "Manhattan", -650, y, lib=SELF_CTX, guid=MANHATTAN_GUID)
        cv = Node("RM_CV" + tag, "Conv_IntToString", -420, y, lib=STR)
        for v, (px, py) in ((va, (ax, ay)), (vb, (bx, by))):
            v.pin("X", "in", T_DOUBLE, "%.1f" % px)
            v.pin("Y", "in", T_DOUBLE, "%.1f" % py)
            v.pin("ReturnValue", "out", T_V2D, None,
                  [(mn.name, mn.pid("A" if v is va else "B"))])
        mn.pin("A", "in", T_V2D, None, [(va.name, va.pid("ReturnValue"))])
        mn.pin("B", "in", T_V2D, None, [(vb.name, vb.pid("ReturnValue"))])
        mn.pin("Distance", "out", T_INT, "0", [(cv.name, cv.pid("InInt"))])
        cv.pin("InInt", "in", T_INT, "0", [(mn.name, mn.pid("Distance"))])
        cv.pin("ReturnValue", "out", T_STR, None)
        nodes.extend([va, vb, mn, cv])
        print_line(tag, "Manhattan (%g,%g)->(%g,%g) expect %s got " % (ax, ay, bx, by, expect),
                   cv, "ReturnValue")

    def inbounds_case(tag, x, y, expect):
        v = Node("RM_IBV" + tag, "MakeVector2D", -900, y_of(), lib=MATH)
        ib = Node("RM_IB" + tag, "InBounds", -650, y_of(), lib=SELF_CTX)
        cb = Node("RM_IBC" + tag, "Conv_BoolToString", -420, y_of(), lib=STR)
        v.pin("X", "in", T_DOUBLE, "%.1f" % x)
        v.pin("Y", "in", T_DOUBLE, "%.1f" % y)
        v.pin("ReturnValue", "out", T_V2D, None, [(ib.name, ib.pid("Tile"))])
        ib.pin("Tile", "in", T_V2D, None, [(v.name, v.pid("ReturnValue"))])
        # The output is "Inside", not "IsInBounds": UE 5.5 refuses that exact
        # name on this Blueprint (the parameter rename silently reverts, while
        # "IsInBound" and "Inside" are both accepted). Whatever holds the name,
        # the pin name here has to match the one on the function or the pasted
        # call nodes orphan their output pin.
        ib.pin("Inside", "out", T_BOOL, None, [(cb.name, cb.pid("InBool"))])
        cb.pin("InBool", "in", T_BOOL, "false", [(ib.name, ib.pid("Inside"))])
        cb.pin("ReturnValue", "out", T_STR, None)
        nodes.extend([v, ib, cb])
        print_line(tag, "InBounds(%g,%g) expect %s got " % (x, y, expect), cb, "ReturnValue")

    def tiletoworld_case(tag, x, y, expect):
        v = Node("RM_TWV" + tag, "MakeVector2D", -900, y_of(), lib=MATH)
        tw = Node("RM_TW" + tag, "TileToWorld", -650, y_of(), lib=SELF_CTX)
        cv = Node("RM_TWC" + tag, "Conv_VectorToString", -420, y_of(), lib=STR)
        v.pin("X", "in", T_DOUBLE, "%.1f" % x)
        v.pin("Y", "in", T_DOUBLE, "%.1f" % y)
        v.pin("ReturnValue", "out", T_V2D, None, [(tw.name, tw.pid("Tile"))])
        tw.pin("Tile", "in", T_V2D, None, [(v.name, v.pid("ReturnValue"))])
        tw.pin("World", "out", T_VEC, None, [(cv.name, cv.pid("InVec"))])
        cv.pin("InVec", "in", T_VEC, None, [(tw.name, tw.pid("World"))])
        cv.pin("ReturnValue", "out", T_STR, None)
        nodes.extend([v, tw, cv])
        print_line(tag, "TileToWorld(%g,%g) expect %s got " % (x, y, expect), cv, "ReturnValue")

    def approach_case(tag, ax, ay, bx, by, expect):
        """Approach is the One Wow's read of "is the dog closing in".

        It is worth asserting even though nothing else calls it yet: GDD 3
        exploit 4 was an approach value that only ever ratcheted upward, and the
        fix was to make it positional -- recomputed from the two tiles on every
        call, storing nothing. A test that feeds it the same pair twice and a
        receding pair is the only thing that keeps that property honest.
        """
        va = Node("RM_APA" + tag, "MakeVector2D", -900, y_of(), lib=MATH)
        vb = Node("RM_APB" + tag, "MakeVector2D", -900, y_of() + 90, lib=MATH)
        ap = Node("RM_AP" + tag, "Approach", -650, y_of(), lib=SELF_CTX)
        cv = Node("RM_APC" + tag, "Conv_DoubleToString", -420, y_of(), lib=STR)
        for v, (px, py) in ((va, (ax, ay)), (vb, (bx, by))):
            v.pin("X", "in", T_DOUBLE, "%.1f" % px)
            v.pin("Y", "in", T_DOUBLE, "%.1f" % py)
            v.pin("ReturnValue", "out", T_V2D, None,
                  [(ap.name, ap.pid("Dog" if v is va else "Kid"))])
        ap.pin("Dog", "in", T_V2D, None, [(va.name, va.pid("ReturnValue"))])
        ap.pin("Kid", "in", T_V2D, None, [(vb.name, vb.pid("ReturnValue"))])
        ap.pin("Approach", "out", T_DOUBLE, None, [(cv.name, cv.pid("InDouble"))])
        cv.pin("InDouble", "in", T_DOUBLE, "0.0", [(ap.name, ap.pid("Approach"))])
        cv.pin("ReturnValue", "out", T_STR, None)
        nodes.extend([va, vb, ap, cv])
        print_line(tag, "Approach (%g,%g)->(%g,%g) expect %s got "
                   % (ax, ay, bx, by, expect), cv, "ReturnValue")

    def steptoward_case(tag, fx, fy, tx, ty, expect):
        """StepToward returns a tile, so the assertion prints "x,y".

        The out-of-bounds case is the one that matters. Predict deliberately
        returns an off-grid tile when the dog is against a fence, so Rex is
        routinely asked to walk toward somewhere that does not exist. game.js
        skips a candidate that fails inBounds and falls through to the next
        direction; if the guard were dropped here Rex would step off the board
        and every later InBounds would read false.
        """
        va = Node("RM_SVA" + tag, "MakeVector2D", -1150, y_of(), lib=MATH)
        vb = Node("RM_SVB" + tag, "MakeVector2D", -1150, y_of() + 90, lib=MATH)
        st = Node("RM_ST" + tag, "StepToward", -900, y_of(), lib=SELF_CTX)
        br = Node("RM_SBR" + tag, "BreakVector2D", -700, y_of(), lib=MATH)
        cx = Node("RM_SCX" + tag, "Conv_DoubleToString", -540, y_of(), lib=STR)
        cy = Node("RM_SCY" + tag, "Conv_DoubleToString", -540, y_of() + 60, lib=STR)
        j1 = Node("RM_SJ1" + tag, "Concat_StrStr", -380, y_of(), lib=STR)
        j2 = Node("RM_SJ2" + tag, "Concat_StrStr", -280, y_of(), lib=STR)
        for v, (px, py), pin in ((va, (fx, fy), "From"), (vb, (tx, ty), "Target")):
            v.pin("X", "in", T_DOUBLE, "%.1f" % px)
            v.pin("Y", "in", T_DOUBLE, "%.1f" % py)
            v.pin("ReturnValue", "out", T_V2D, None, [(st.name, st.pid(pin))])
        st.pin("From", "in", T_V2D, None, [(va.name, va.pid("ReturnValue"))])
        st.pin("Target", "in", T_V2D, None, [(vb.name, vb.pid("ReturnValue"))])
        st.pin("Step", "out", T_V2D, None, [(br.name, br.pid("InVec"))])
        br.pin("InVec", "in", T_V2D, None, [(st.name, st.pid("Step"))])
        br.pin("X", "out", T_DOUBLE, "0.0", [(cx.name, cx.pid("InDouble"))])
        br.pin("Y", "out", T_DOUBLE, "0.0", [(cy.name, cy.pid("InDouble"))])
        cx.pin("InDouble", "in", T_DOUBLE, "0.0", [(br.name, br.pid("X"))])
        cx.pin("ReturnValue", "out", T_STR, None, [(j1.name, j1.pid("A"))])
        cy.pin("InDouble", "in", T_DOUBLE, "0.0", [(br.name, br.pid("Y"))])
        cy.pin("ReturnValue", "out", T_STR, None, [(j2.name, j2.pid("B"))])
        j1.pin("A", "in", T_STR, None, [(cx.name, cx.pid("ReturnValue"))])
        j1.pin("B", "in", T_STR, ",")
        j1.pin("ReturnValue", "out", T_STR, None, [(j2.name, j2.pid("A"))])
        j2.pin("A", "in", T_STR, None, [(j1.name, j1.pid("ReturnValue"))])
        j2.pin("B", "in", T_STR, None, [(cy.name, cy.pid("ReturnValue"))])
        j2.pin("ReturnValue", "out", T_STR, None)
        nodes.extend([va, vb, st, br, cx, cy, j1, j2])
        print_line(tag, "StepToward (%g,%g)->(%g,%g) expect %s got "
                   % (fx, fy, tx, ty, expect), j2, "ReturnValue")

    def veto_case():
        """The One Wow, asserted.

        Dog at (0,0), Rex at (0,1), one "right" in the move history. Predict
        reads that as the dog stepping to (1,0), and StepToward(Rex, (1,0))
        goes right, to (1,1) -- which is two tiles from the dog when Rex was
        one tile away. Rex would have followed its own prediction away from
        the thing it is chasing.

        The veto catches exactly that and falls back to StepToward(Rex, Dog),
        which is (0,0). So a passing run prints 0.0,0.0 and a build with the
        veto removed prints 1.0,1.0 -- the assertion fails loudly rather than
        the fight quietly becoming free, which is GDD 6.1's whole point.

        Charge is checked in the same breath: Rex moved, so it pays PursuitCost
        8 and recovers SolarRecovery 2, 100 - 8 + 2 = 94.
        """
        nonlocal prev_print, y
        # A struct pin literal serialises as UE writes it: "(X=..,Y=..)".
        setdog = VarSet("RM_VtDog", "DogTile", T_V2D, -1300, y_of(),
                        value_default="(X=0.000000,Y=0.000000)")
        setrex = VarSet("RM_VtRex", "RexTile", T_V2D, -1100, y_of(),
                        value_default="(X=0.000000,Y=1.000000)")
        moves = VarGet("RM_VtMoves", "Moves",
                       'PinType.PinCategory="string",PinType.PinSubCategory="",'
                       'PinType.PinSubCategoryObject=None',
                       -1000, y_of() + 120, tail=TAIL_ARRAY)
        add = ArrayAdd("RM_VtAdd", -900, y_of())
        act = Node("RM_VtAct", "RexAct", -700, y_of(), lib=SELF_CTX, pure=False)
        act.pin("execute", "in", T_EXEC)
        act.pin("then", "out", T_EXEC)
        act.pin("Predicted", "out", T_V2D)

        # dog (0,0) and rex (0,1) go in as pin literals on the setters
        setdog.value_links = []
        setrex.value_links = []
        nodes.extend([setdog, setrex, moves, add, act])

        head = prev_print if prev_print is not None else begin
        setdog.exec_in.append((head.name, head.pid("then")))
        if prev_print is None:
            begin.pin("then", "out", T_EXEC, None, [(setdog.name, setdog.pid("execute"))])
        else:
            for i, t in enumerate(prev_print.pins):
                if t[0] == "then":
                    prev_print.pins[i] = (t[:4]
                                          + ([(setdog.name, setdog.pid("execute"))],)
                                          + t[5:])
        setdog.exec_out.append((setrex.name, setrex.pid("execute")))
        setrex.exec_in.append((setdog.name, setdog.pid("then")))
        setch = VarSet("RM_VtSetCh", "Charge", T_DOUBLE, -1000, y_of() - 80,
                       value_default="100.0")
        nodes.append(setch)
        setrex.exec_out.append((setch.name, setch.pid("execute")))
        setch.exec_in.append((setrex.name, setrex.pid("then")))
        setch.exec_out.append((add.name, add.pid("execute")))
        add.exec_in.append((setch.name, setch.pid("then")))
        add.exec_out.append((act.name, act.pid("execute")))
        act.pins[0] = act.pins[0][:4] + ([(add.name, add.pid("then"))],) + act.pins[0][5:]
        add.array_links.append((moves.name, moves.out_pin()))
        moves.links.append((add.name, add.pid("TargetArray")))
        add.item_default = "right"

        prev_print = act          # the next print chains off RexAct's then

        # read the tile back and print it
        rex = VarGet("RM_VtOut", "RexTile", T_V2D, -500, y_of() + 140)
        br = Node("RM_VtBr", "BreakVector2D", -380, y_of() + 140)
        cx = Node("RM_VtCX", "Conv_DoubleToString", -260, y_of() + 140, lib=STR)
        cy = Node("RM_VtCY", "Conv_DoubleToString", -260, y_of() + 200, lib=STR)
        j1 = Node("RM_VtJ1", "Concat_StrStr", -140, y_of() + 140, lib=STR)
        j2 = Node("RM_VtJ2", "Concat_StrStr", -60, y_of() + 140, lib=STR)
        br.pin("InVec", "in", T_V2D, None, [(rex.name, rex.out_pin())])
        rex.links.append((br.name, br.pid("InVec")))
        br.pin("X", "out", T_DOUBLE, "0.0", [(cx.name, cx.pid("InDouble"))])
        br.pin("Y", "out", T_DOUBLE, "0.0", [(cy.name, cy.pid("InDouble"))])
        cx.pin("InDouble", "in", T_DOUBLE, "0.0", [(br.name, br.pid("X"))])
        cx.pin("ReturnValue", "out", T_STR, None, [(j1.name, j1.pid("A"))])
        cy.pin("InDouble", "in", T_DOUBLE, "0.0", [(br.name, br.pid("Y"))])
        cy.pin("ReturnValue", "out", T_STR, None, [(j2.name, j2.pid("B"))])
        j1.pin("A", "in", T_STR, None, [(cx.name, cx.pid("ReturnValue"))])
        j1.pin("B", "in", T_STR, ",")
        j1.pin("ReturnValue", "out", T_STR, None, [(j2.name, j2.pid("A"))])
        j2.pin("A", "in", T_STR, None, [(j1.name, j1.pid("ReturnValue"))])
        j2.pin("B", "in", T_STR, None, [(cy.name, cy.pid("ReturnValue"))])
        j2.pin("ReturnValue", "out", T_STR, None)
        nodes.extend([rex, br, cx, cy, j1, j2])
        print_line("V", "RexAct veto: dog(0,0) rex(0,1) moves[right] "
                        "expect rex 0.0,0.0 got ", j2, "ReturnValue")

        ch = VarGet("RM_VtCh", "Charge", T_DOUBLE, -500, y_of() + 140)
        cc = Node("RM_VtCC", "Conv_DoubleToString", -300, y_of() + 140, lib=STR)
        cc.pin("InDouble", "in", T_DOUBLE, "0.0", [(ch.name, ch.out_pin())])
        ch.links.append((cc.name, cc.pid("InDouble")))
        cc.pin("ReturnValue", "out", T_STR, None)
        nodes.extend([ch, cc])
        print_line("W", "RexAct charge: expect 94 got ", cc, "ReturnValue")

    def round_case():
        """Drive OnPlayerMove twice and check what the round did.

        The first move is into the fence. The dog spawns at (0,0) and "up" is
        (0,-1), so the target is off the grid: the round must NOT advance and
        the dog must NOT move. That is RM-003, and it is the only assertion
        here that can catch the Branch being wired to the wrong exec pin --
        a graph with the true and false paths swapped compiles perfectly and
        simply lets the dog walk through the fence.

        The second move is legal and everything advances by one.

        This also covers the input path indirectly: the nine key events call
        OnPlayerMove with exactly these strings and nothing else, so if this
        passes, pressing D does what pressing D should.
        """
        nonlocal prev_print, y

        def drive(tag, direction, expect):
            nonlocal prev_print
            mv = Node("RM_Rd%s" % tag, "OnPlayerMove", -1100, y_of(),
                      lib=SELF_CTX, pure=False)
            mv.pin("execute", "in", T_EXEC)
            mv.pin("then", "out", T_EXEC)
            mv.pin("Direction", "in", T_STR, direction)
            head = prev_print
            mv.pins[0] = mv.pins[0][:4] + ([(head.name, head.pid("then"))],) + mv.pins[0][5:]
            # VarSet keeps its exec links in a list; Node keeps them in pins.
            if hasattr(head, "exec_out"):
                head.exec_out.append((mv.name, mv.pid("execute")))
            else:
                for i, t in enumerate(head.pins):
                    if t[0] == "then":
                        head.pins[i] = t[:4] + ([(mv.name, mv.pid("execute"))],) + t[5:]
            nodes.append(mv)
            prev_print = mv

            dog = VarGet("RM_RdDog%s" % tag, "DogTile", T_V2D, -900, y_of() + 120)
            br = Node("RM_RdBr%s" % tag, "BreakVector2D", -780, y_of() + 120)
            cx = Node("RM_RdCX%s" % tag, "Conv_DoubleToString", -650, y_of() + 120, lib=STR)
            cy = Node("RM_RdCY%s" % tag, "Conv_DoubleToString", -650, y_of() + 180, lib=STR)
            rnd = VarGet("RM_RdRnd%s" % tag, "Round", T_INT, -900, y_of() + 240)
            ci = Node("RM_RdCI%s" % tag, "Conv_IntToString", -650, y_of() + 240, lib=STR)
            j1 = Node("RM_RdJ1%s" % tag, "Concat_StrStr", -500, y_of() + 120, lib=STR)
            j2 = Node("RM_RdJ2%s" % tag, "Concat_StrStr", -420, y_of() + 120, lib=STR)
            j3 = Node("RM_RdJ3%s" % tag, "Concat_StrStr", -340, y_of() + 120, lib=STR)
            br.pin("InVec", "in", T_V2D, None, [(dog.name, dog.out_pin())])
            dog.links.append((br.name, br.pid("InVec")))
            br.pin("X", "out", T_DOUBLE, "0.0", [(cx.name, cx.pid("InDouble"))])
            br.pin("Y", "out", T_DOUBLE, "0.0", [(cy.name, cy.pid("InDouble"))])
            cx.pin("InDouble", "in", T_DOUBLE, "0.0", [(br.name, br.pid("X"))])
            cx.pin("ReturnValue", "out", T_STR, None, [(j1.name, j1.pid("A"))])
            cy.pin("InDouble", "in", T_DOUBLE, "0.0", [(br.name, br.pid("Y"))])
            cy.pin("ReturnValue", "out", T_STR, None, [(j2.name, j2.pid("B"))])
            ci.pin("InInt", "in", T_INT, "0", [(rnd.name, rnd.out_pin())])
            rnd.links.append((ci.name, ci.pid("InInt")))
            ci.pin("ReturnValue", "out", T_STR, None, [(j3.name, j3.pid("B"))])
            j1.pin("A", "in", T_STR, None, [(cx.name, cx.pid("ReturnValue"))])
            j1.pin("B", "in", T_STR, ",")
            j1.pin("ReturnValue", "out", T_STR, None, [(j2.name, j2.pid("A"))])
            j2.pin("A", "in", T_STR, None, [(j1.name, j1.pid("ReturnValue"))])
            j2.pin("B", "in", T_STR, None, [(cy.name, cy.pid("ReturnValue"))])
            j2.pin("ReturnValue", "out", T_STR, None,
                   [("RM_RdSep%s" % tag, guid("RM_RdSep%s::A" % tag))])
            # A literal on a pin that is also connected is ignored, so " round "
            # needs a concat of its own rather than sharing the pin with ci.
            jsep = Node("RM_RdSep%s" % tag, "Concat_StrStr", -380, y_of() + 120, lib=STR)
            jsep.pin("A", "in", T_STR, None, [(j2.name, j2.pid("ReturnValue"))])
            jsep.pin("B", "in", T_STR, " round ")
            jsep.pin("ReturnValue", "out", T_STR, None, [(j3.name, j3.pid("A"))])
            j3.pin("A", "in", T_STR, None, [(jsep.name, jsep.pid("ReturnValue"))])
            j3.pin("B", "in", T_STR, None, [(ci.name, ci.pid("ReturnValue"))])
            j3.pin("ReturnValue", "out", T_STR, None)
            nodes.extend([dog, br, cx, cy, rnd, ci, j1, j2, jsep, j3])
            print_line("R" + tag, "OnPlayerMove(%s) expect %s got dog " % (direction, expect),
                       j3, "ReturnValue")

        # A full reset, not just the three values the assertions read.
        # OnPlayerMove now ends on SpeakRead and CheckEnd, so leftovers from
        # veto_case decide whether the robot speaks and whether the fight is
        # already over: Charge 0 would put the band at strained and fire the
        # charge_strain read, Stamina 0 would make CheckEnd declare a loss on
        # the first legal move, and Moves would still hold veto_case's "right".
        set_var("RdSetDog", "DogTile", T_V2D, "(X=0.000000,Y=0.000000)", -1400)
        set_var("RdSetRex", "RexTile", T_V2D, "(X=5.000000,Y=5.000000)", -1260)
        set_var("RdSetRnd", "Round", T_INT, "0", -1120)
        set_var("RdSetCh", "Charge", T_DOUBLE, "100.0", -980)
        set_var("RdSetSt", "Stamina", T_INT, "15", -840)
        set_var("RdSetEnd", "Ended", T_BOOL, "false", -700)
        set_var("RdSetLc", "LastCatIndex", T_INT, "-1", -560)
        clear_var("RdSetMv", "Moves", -420)
        clear_var("RdSetSp", "SpokenLines", -280)

        drive("A", "up", "dog 0.0,0.0 round 0 (refused)")
        drive("B", "right", "dog 1.0,0.0 round 1")

    def speak_case(tag, moves, charge, limping, expect_cat, expect_line):
        """SpeakRead, run against a hand-built move history.

        Three things get pinned here, and they are the three findings that made
        the graph small enough to build at all (docs/UNREAL-SPEECH-PLAN.md):

        - the row is `band * 8 + category` arithmetic, so a wrong index shows up
          as the wrong sentence rather than as nothing at all;
        - the counts come from measuring what disappears when a word is removed
          from the joined history, so three lefts have to read as three;
        - RM-001's guard. Every sealing_direction line names "left", so the
          trigger may only fire when left dominates. A dog that ran right must
          be told nothing, and `expect_cat -1` is that assertion.

        LastCatIndex is what gets read back, because SpeakRead has no return
        value: it prints, then records. SpokenLines is joined rather than
        indexed so the silent case reads as an empty string instead of logging
        an out-of-range warning.
        """
        clear_var("Sk%sMv" % tag, "Moves", -1500)
        clear_var("Sk%sSp" % tag, "SpokenLines", -1360)
        set_var("Sk%sCh" % tag, "Charge", T_DOUBLE, "%.1f" % charge, -1220)
        set_var("Sk%sLp" % tag, "Limping", T_BOOL, "true" if limping else "false", -1080)
        set_var("Sk%sLc" % tag, "LastCatIndex", T_INT, "-1", -940)

        mv = VarGet("RM_Sk%sGet" % tag, "Moves", T_STRING_ELEM, -800, y_of() + 300,
                    tail=TAIL_ARRAY)
        nodes.append(mv)
        for mi, word in enumerate(moves):
            add = ArrayAdd("RM_Sk%sAdd%d" % (tag, mi), -800 + mi * 140, y_of())
            add.item_default = word
            add.array_links.append((mv.name, mv.out_pin()))
            mv.links.append((add.name, add.pid("TargetArray")))
            chain(add)

        sr = Node("RM_Sk%sRun" % tag, "SpeakRead", 100, y_of(), lib=SELF_CTX, pure=False)
        sr.pin("execute", "in", T_EXEC)
        sr.pin("then", "out", T_EXEC)
        chain(sr)

        cat = VarGet("RM_Sk%sCat" % tag, "LastCatIndex", T_INT, -800, y_of() + 380)
        ci = Node("RM_Sk%sCi" % tag, "Conv_IntToString", -650, y_of() + 380, lib=STR)
        ci.pin("InInt", "in", T_INT, "0", [(cat.name, cat.out_pin())])
        cat.links.append((ci.name, ci.pid("InInt")))
        ci.pin("ReturnValue", "out", T_STR, None)

        sp = VarGet("RM_Sk%sSpk" % tag, "SpokenLines", T_STRING_ELEM, -800,
                    y_of() + 460, tail=TAIL_ARRAY)
        jn = Node("RM_Sk%sJn" % tag, "JoinStringArray", -650, y_of() + 460, lib=STR)
        jn.pin("SourceArray", "in", T_STRING_ELEM, None,
               [(sp.name, sp.out_pin())], TAIL_ARRAY_REF)
        sp.links.append((jn.name, jn.pid("SourceArray")))
        jn.pin("Separator", "in", T_STR, "")
        jn.pin("ReturnValue", "out", T_STR, None)

        sep = Node("RM_Sk%sSep" % tag, "Concat_StrStr", -480, y_of() + 380, lib=STR)
        sep.pin("A", "in", T_STR, None, [(ci.name, ci.pid("ReturnValue"))])
        ci.pins[1] = ci.pins[1][:4] + ([(sep.name, sep.pid("A"))],) + ci.pins[1][5:]
        sep.pin("B", "in", T_STR, " / ")
        sep.pin("ReturnValue", "out", T_STR, None)
        both = Node("RM_Sk%sBoth" % tag, "Concat_StrStr", -340, y_of() + 380, lib=STR)
        both.pin("A", "in", T_STR, None, [(sep.name, sep.pid("ReturnValue"))])
        sep.pins[2] = sep.pins[2][:4] + ([(both.name, both.pid("A"))],) + sep.pins[2][5:]
        both.pin("B", "in", T_STR, None, [(jn.name, jn.pid("ReturnValue"))])
        jn.pins[2] = jn.pins[2][:4] + ([(both.name, both.pid("B"))],) + jn.pins[2][5:]
        both.pin("ReturnValue", "out", T_STR, None)
        nodes.extend([cat, ci, sp, jn, sep, both])

        print_line("Sk" + tag, "SpeakRead [%s] charge %g expect %d / %s got "
                   % (",".join(moves) or "-", charge, expect_cat, expect_line),
                   both, "ReturnValue")

    def checkend_case(tag, dx, dy, rnd, stamina, expect):
        """CheckEnd, one ending at a time.

        Arrival is checked before stamina on purpose, so reaching the kid on
        your last legs still counts as a win. The win case runs with stamina at
        zero, which is the only way to tell that order was kept.

        `Ended` is written false first because an earlier case may have set it,
        and a fight that has already ended does not end again.
        """
        set_var("Ce%sDog" % tag, "DogTile", T_V2D,
                "(X=%f,Y=%f)" % (dx, dy), -1500)
        set_var("Ce%sRnd" % tag, "Round", T_INT, str(rnd), -1360)
        set_var("Ce%sSt" % tag, "Stamina", T_INT, str(stamina), -1220)
        set_var("Ce%sEnd" % tag, "Ended", T_BOOL, "false", -1080)

        ce = Node("RM_Ce%sRun" % tag, "CheckEnd", -900, y_of(), lib=SELF_CTX, pure=False)
        ce.pin("execute", "in", T_EXEC)
        ce.pin("then", "out", T_EXEC)
        chain(ce)

        got = VarGet("RM_Ce%sGot" % tag, "Ended", T_BOOL, -700, y_of() + 300)
        cb = Node("RM_Ce%sCb" % tag, "Conv_BoolToString", -550, y_of() + 300, lib=STR)
        cb.pin("InBool", "in", T_BOOL, "false", [(got.name, got.out_pin())])
        got.links.append((cb.name, cb.pid("InBool")))
        cb.pin("ReturnValue", "out", T_STR, None)
        nodes.extend([got, cb])
        print_line("Ce" + tag, "CheckEnd dog(%g,%g) round %d stamina %d "
                              "expect ended %s got " % (dx, dy, rnd, stamina, expect),
                   cb, "ReturnValue")

    def band_case(tag, charge, expect):
        bd = Node("RM_BD" + tag, "Band", -650, y, lib=SELF_CTX)
        bd.pin("Charge", "in", T_DOUBLE, "%.1f" % charge)
        bd.pin("BandName", "out", T_STR, None)
        nodes.append(bd)
        print_line(tag, "Band(%g) expect %s got " % (charge, expect), bd, "BandName")

    manhattan_case("0", 0, 0, 7, 4, "11")
    manhattan_case("1", 9, 9, 0, 0, "18")
    band_case("2", 100, "clinical")
    band_case("3", 60, "confident")    # boundary: > 60 is clinical, so 60 is not
    band_case("4", 45, "confident")
    band_case("5", 30, "confident")    # boundary: >= 30
    band_case("6", 29, "strained")
    band_case("7", 10, "strained")
    # InBounds: the grid is 10x10, so 0..9 is inside and anything else is not
    inbounds_case("8", 0, 0, "true")
    inbounds_case("9", 9, 9, "true")
    inbounds_case("A", 10, 0, "false")
    inbounds_case("B", 0, 10, "false")
    inbounds_case("C", -1, 5, "false")
    # TileToWorld: pins the 200 that is duplicated in ue_build_arena.py
    tiletoworld_case("D", 0, 0, "X=0 Y=0 Z=0")
    tiletoworld_case("E", 7, 4, "X=1400 Y=800 Z=0")
    # Approach: 1 - Manhattan/11, clamped 0..1. The dog spawns exactly 11 tiles
    # from the kid, which is why the divisor is 11 and why spawn reads 0.
    approach_case("F", 0, 0, 7, 4, "0")          # spawn
    approach_case("G", 7, 4, 7, 4, "1")          # standing on the kid
    approach_case("H", 6, 4, 7, 4, "0.909091")   # one tile out
    approach_case("I", 9, 9, 0, 0, "0 (clamped)")  # 18 tiles: 1-18/11 is negative
    # StepToward: game.js tries left, right, up, down and keeps the first that
    # closes the gap, so X is preferred over Y whenever both differ.
    steptoward_case("J", 5, 5, 5, 5, "5.0,5.0")    # already there, do not move
    steptoward_case("K", 5, 5, 7, 4, "6.0,5.0")    # both differ: X wins
    steptoward_case("L", 5, 5, 5, 2, "5.0,4.0")    # dx is 0, so Y moves
    steptoward_case("M", 0, 3, -1, 0, "0.0,2.0")   # left is off-grid: falls to up
    steptoward_case("N", 9, 9, 9, 0, "9.0,8.0")    # against the far fence
    # Last, because unlike every case above it writes state: it sets DogTile,
    # RexTile and Moves so that following the prediction would walk Rex away
    # from the dog, and then checks that the veto did not let it.
    veto_case()
    # Last of all, because it drives the real round loop and leaves the fight
    # mid-game: dog one tile east of spawn, one round on the clock.
    round_case()
    # SpeakRead, after round_case because it needs a move history it controls.
    # Row indices come straight from DT_NemesisReads' import order: the table
    # is eight categories by three bands, sealing_direction first and clinical
    # first, so clinical sealing_direction is row 0 and clinical stall is row 4.
    speak_case("A", ["left", "left", "left"], 100, False, 0,
               "Target favored left nine of twenty recorded moves.")
    # RM-001. Same shape, opposite direction, and the robot has to stay quiet.
    # Both sides of the slash are empty when nothing was spoken.
    speak_case("B", ["right", "right", "right"], 100, False, -1, "")
    speak_case("C", ["wait", "wait"], 100, False, 4,
               "Two of the last four moves cancelled out.")
    # CheckEnd. The win runs at zero stamina on purpose: arrival is tested
    # before exhaustion, and this is the only case that can tell.
    checkend_case("A", 7, 4, 0, 0, "true")
    checkend_case("B", 0, 0, 15, 15, "true")
    checkend_case("C", 0, 0, 3, 15, "false")
    return nodes


